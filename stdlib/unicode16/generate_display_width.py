#!/usr/bin/env python3
"""Generate Unicode16 display-width ranges (EAW W/F union P1868R2)."""
from pathlib import Path
import argparse
import hashlib

HERE = Path(__file__).resolve().parent
TARGET = HERE.parent / 'std@1' / 'display_width_tables.hir'
INPUT = HERE / 'EastAsianWidth.txt'
# P1868R2 section 15; these ranges deliberately include unassigned scalars.
P1868 = [(0x1100, 0x115f), (0x2329, 0x232a), (0x2e80, 0x303e),
         (0x3040, 0xa4cf), (0xac00, 0xd7a3), (0xf900, 0xfaff),
         (0xfe10, 0xfe19), (0xfe30, 0xfe6f), (0xff00, 0xff60),
         (0xffe0, 0xffe6), (0x20000, 0x2fffd), (0x30000, 0x3fffd),
         (0x1f300, 0x1f64f), (0x1f900, 0x1f9ff)]


def generate():
    wide = bytearray(0x110000)
    ranges = list(P1868)
    for line in INPUT.read_text().splitlines():
        fields = [part.strip() for part in line.split('#')[0].split(';')]
        if len(fields) < 2 or fields[1] not in ('W', 'F'):
            continue
        ends = fields[0].split('..')
        ranges.append((int(ends[0], 16), int(ends[-1], 16)))
    for first, last in ranges:
        wide[first:last + 1] = bytes([1]) * (last - first + 1)
    rows = []
    first = 0
    while first < len(wide):
        last = first + 1
        while last < len(wide) and wide[last] == wide[first]:
            last += 1
        if wide[first]:
            rows.append((first, last - 1))
        first = last
    data = b''.join(a.to_bytes(3, 'big') + b.to_bytes(3, 'big') for a, b in rows)
    return '\n'.join([
        '// Generated by stdlib/unicode16/generate_display_width.py; Unicode 16.0.0.',
        '// EAW W/F union P1868R2 section 15; Unicode license: ../unicode16/LICENSE.txt.',
        f'// EastAsianWidth.txt SHA-256: {hashlib.sha256(INPUT.read_bytes()).hexdigest()}',
        f'// {len(rows)} disjoint sorted rows: inclusive first, inclusive last.',
        'const DISPLAY_WIDE: Bytes = b"' + ''.join(f'\\x{b:02x}' for b in data) + '"', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = generate()
    if args.check:
        assert TARGET.read_text() == source, 'Display-width source tables need regeneration'
    else:
        TARGET.write_text(source)
