#!/usr/bin/env python3
"""Regenerate ordinary Hirsel NFC tables from the vendored Unicode 16 UCD."""
from pathlib import Path
import hashlib

HERE = Path(__file__).resolve().parent
TARGET = HERE.parent / 'std@1' / 'unicode_tables.hir'

def tables():
    classes, decompositions, exclusions = [], [], set()
    for line in (HERE / 'DerivedNormalizationProps.txt').read_text().splitlines():
        fields = line.split('#')[0].strip().split(';')
        if len(fields) < 2 or fields[1].strip() != 'Full_Composition_Exclusion':
            continue
        bounds = fields[0].strip().split('..')
        exclusions.update(range(int(bounds[0], 16), int(bounds[-1], 16) + 1))
    for line in (HERE / 'UnicodeData.txt').read_text().splitlines():
        fields = line.split(';')
        cp, ccc, mapping = int(fields[0], 16), int(fields[3]), fields[5]
        if ccc:
            classes.append((cp, ccc))
        if mapping and not mapping.startswith('<'):
            parts = [int(x, 16) for x in mapping.split()]
            assert 1 <= len(parts) <= 2
            decompositions.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
    compositions = sorted((a, b, cp) for cp, a, b in decompositions if b and cp not in exclusions)
    assert len({(a, b) for a, b, _ in compositions}) == len(compositions)
    return classes, decompositions, compositions

def generate():
    classes, decompositions, compositions = tables()
    lines = ['// Generated by stdlib/unicode16/generate.py; Unicode 16.0.0.',
             '// Three-byte big-endian scalar fields; CCC is one byte.',
             '// Sorted fixed-width rows support allocation-free binary search.',
             '// Unicode data license: ../unicode16/LICENSE.txt.']
    for name in ['UnicodeData.txt', 'DerivedNormalizationProps.txt']:
        digest = hashlib.sha256((HERE / name).read_bytes()).hexdigest()
        lines.append(f'// {name} SHA-256: {digest}')
    for name, rows, widths in [('NFC_CCC', classes, [3, 1]),
                              ('NFC_DECOMPOSITION', decompositions, [3, 3, 3]),
                              ('NFC_COMPOSITION', compositions, [3, 3, 3])]:
        data = b''.join(value.to_bytes(width, 'big') for row in rows for value, width in zip(row, widths))
        lines += [f'// {len(rows)} rows: ' + {'NFC_CCC': 'scalar, combining class',
                  'NFC_DECOMPOSITION': 'scalar, canonical first, canonical second (zero for singleton)',
                  'NFC_COMPOSITION': 'first, second, composite; Full_Composition_Exclusion removed'}[name],
                  f'const {name}: Bytes = b"' + ''.join(f'\\x{x:02x}' for x in data) + '"', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = generate()
    if args.check:
        assert TARGET.read_text() == source, 'NFC source tables need regeneration'
    else:
        TARGET.write_text(source)
