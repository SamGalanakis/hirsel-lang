#!/usr/bin/env python3
"""Regenerate ordinary Hirsel NFC/property tables from the vendored Unicode 16 UCD."""
from pathlib import Path
import hashlib

HERE = Path(__file__).resolve().parent
TARGET = HERE.parent / 'std@1' / 'unicode_tables.hir'

def tables():
    classes, decompositions, exclusions = [], [], set()
    for line in (HERE / 'DerivedNormalizationProps.txt').read_text().splitlines():
        fields = line.split('#')[0].strip().split(';')
        if len(fields) < 2 or fields[1].strip() != 'Full_Composition_Exclusion':
            continue
        bounds = fields[0].strip().split('..')
        exclusions.update(range(int(bounds[0], 16), int(bounds[-1], 16) + 1))
    for line in (HERE / 'UnicodeData.txt').read_text().splitlines():
        fields = line.split(';')
        cp, ccc, mapping = int(fields[0], 16), int(fields[3]), fields[5]
        if ccc:
            classes.append((cp, ccc))
        if mapping and not mapping.startswith('<'):
            parts = [int(x, 16) for x in mapping.split()]
            assert 1 <= len(parts) <= 2
            decompositions.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
    compositions = sorted((a, b, cp) for cp, a, b in decompositions if b and cp not in exclusions)
    assert len({(a, b) for a, b, _ in compositions}) == len(compositions)
    return classes, decompositions, compositions

def generate():
    classes, decompositions, compositions = tables()
    lines = ['// Generated by stdlib/unicode16/generate.py; Unicode 16.0.0.',
             '// Three-byte big-endian scalar fields; CCC is one byte.',
             '// Sorted fixed-width rows support allocation-free binary search.',
             '// Unicode data license: ../unicode16/LICENSE.txt.']
    for name in ['UnicodeData.txt', 'DerivedNormalizationProps.txt']:
        digest = hashlib.sha256((HERE / name).read_bytes()).hexdigest()
        lines.append(f'// {name} SHA-256: {digest}')
    for name, rows, widths in [('NFC_CCC', classes, [3, 1]),
                              ('NFC_DECOMPOSITION', decompositions, [3, 3, 3]),
                              ('NFC_COMPOSITION', compositions, [3, 3, 3])]:
        data = b''.join(value.to_bytes(width, 'big') for row in rows for value, width in zip(row, widths))
        lines += [f'// {len(rows)} rows: ' + {'NFC_CCC': 'scalar, combining class',
                  'NFC_DECOMPOSITION': 'scalar, canonical first, canonical second (zero for singleton)',
                  'NFC_COMPOSITION': 'first, second, composite; Full_Composition_Exclusion removed'}[name],
                  f'const {name}: Bytes = b"' + ''.join(f'\\x{x:02x}' for x in data) + '"', '']
    return '\n'.join(lines)

def generate_properties():
    """Unicode16 L*, Nd, White_Space and simple (one-scalar) case mappings."""
    letters, digits, lower, upper, whitespace = [], [], [], [], []
    first = None
    for line in (HERE / 'UnicodeData.txt').read_text().splitlines():
        fields = line.split(';')
        cp = int(fields[0], 16)
        if fields[1].endswith(', First>'):
            first = cp
            continue
        start = first if fields[1].endswith(', Last>') else cp
        first = None
        if fields[2].startswith('L'):
            letters.append((start, cp))
        if fields[2] == 'Nd':
            digits.append((start, cp))
        if fields[13]:
            lower.append((cp, int(fields[13], 16)))
        if fields[12]:
            upper.append((cp, int(fields[12], 16)))
    for line in (HERE / 'PropList.txt').read_text().splitlines():
        fields = line.split('#')[0].strip().split(';')
        if len(fields) == 2 and fields[1].strip() == 'White_Space':
            bounds = fields[0].strip().split('..')
            whitespace.append((int(bounds[0], 16), int(bounds[-1], 16)))
    def merge(rows):
        result = []
        for start, end in sorted(rows):
            if result and start == result[-1][1] + 1:
                result[-1] = (result[-1][0], end)
            else:
                result.append((start, end))
        return result
    lines = ['// Generated by stdlib/unicode16/generate.py; Unicode 16.0.0.',
             '// Six-byte rows: three-byte big-endian inclusive endpoints or scalar mapping.',
             '// Unicode data license: ../unicode16/LICENSE.txt.']
    for name in ['UnicodeData.txt', 'PropList.txt']:
        lines.append(f'// {name} SHA-256: {hashlib.sha256((HERE / name).read_bytes()).hexdigest()}')
    for name, rows in [('LETTERS', merge(letters)), ('DIGITS', merge(digits)),
                       ('WHITE_SPACE', merge(whitespace)), ('SIMPLE_LOWER', lower),
                       ('SIMPLE_UPPER', upper)]:
        data = b''.join(a.to_bytes(3, 'big') + b.to_bytes(3, 'big') for a, b in rows)
        lines.extend([f'// {len(rows)} rows.', f'const {name}: Bytes = b"' + ''.join(f'\\x{x:02x}' for x in data) + '"', ''])
    return '\n'.join(lines)

if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = {
        TARGET: generate(),
        HERE.parent / 'std@1' / 'unicode_property_tables.hir': generate_properties(),
    }
    for target, source in outputs.items():
        if args.check:
            assert target.read_text() == source, f'{target.name} needs regeneration'
        else:
            target.write_text(source)
