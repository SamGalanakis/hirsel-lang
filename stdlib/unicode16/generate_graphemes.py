#!/usr/bin/env python3
"""Generate Unicode16 extended-grapheme property ranges as ordinary source."""
from pathlib import Path
import hashlib
import argparse

HERE = Path(__file__).resolve().parent
TARGET = HERE.parent / 'std@1' / 'grapheme_tables.hir'
INPUTS = ['GraphemeBreakProperty.txt', 'DerivedCoreProperties.txt', 'emoji-data.txt']
GCB = {'CR': 1, 'LF': 2, 'Control': 3, 'Extend': 4, 'ZWJ': 5,
       'Regional_Indicator': 6, 'Prepend': 7, 'SpacingMark': 8,
       'L': 9, 'V': 10, 'T': 11, 'LV': 12, 'LVT': 13}


def generate():
    properties = bytearray(0x110000)
    for name in INPUTS:
        for line in (HERE / name).read_text().splitlines():
            fields = [s.strip() for s in line.split('#')[0].split(';')]
            if len(fields) < 2:
                continue
            if name == INPUTS[0]:
                value = GCB[fields[1]]
            elif name == INPUTS[1]:
                if fields[1] != 'InCB' or len(fields) < 3:
                    continue
                value = {'Consonant': 16, 'Extend': 32, 'Linker': 48}[fields[2]]
            else:
                if fields[1] != 'Extended_Pictographic':
                    continue
                value = 64
            ends = fields[0].split('..')
            lo, hi = int(ends[0], 16), int(ends[-1], 16)
            for cp in range(lo, hi + 1):
                properties[cp] |= value
    # Hangul syllable GCB is computed in source; it needs no 798 table ranges.
    assert all(properties[cp] == (12 if (cp - 0xac00) % 28 == 0 else 13)
               for cp in range(0xac00, 0xd7a4))
    properties[0xac00:0xd7a4] = bytes(0xd7a4 - 0xac00)
    rows = []
    lo = 0
    while lo < len(properties):
        hi = lo + 1
        while hi < len(properties) and properties[hi] == properties[lo]:
            hi += 1
        if properties[lo]:
            rows.append((lo, hi - 1, properties[lo]))
        lo = hi
    data = b''.join(a.to_bytes(3, 'big') + b.to_bytes(3, 'big') + bytes([p])
                    for a, b, p in rows)
    lines = ['// Generated by stdlib/unicode16/generate_graphemes.py; Unicode 16.0.0.',
             '// UAX #29 revision 45; Unicode license: ../unicode16/LICENSE.txt.',
             '// GCB low four bits (Other=0, CR=1, LF=2, Control=3, Extend=4,',
             '// ZWJ=5, RI=6, Prepend=7, SpacingMark=8, L=9, V=10, T=11, LV=12, LVT=13).',
             '// InCB bits 4..5 (None=0, Consonant=1, Extend=2, Linker=3); EP bit 6.']
    for name in INPUTS:
        lines.append(f'// {name} SHA-256: {hashlib.sha256((HERE / name).read_bytes()).hexdigest()}')
    lines += [f'// {len(rows)} disjoint sorted rows: inclusive first, inclusive last, properties.',
              'const GRAPHEME_PROPERTIES: Bytes = b"' + ''.join(f'\\x{b:02x}' for b in data) + '"', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = generate()
    if args.check:
        assert TARGET.read_text() == source, 'Grapheme source tables need regeneration'
    else:
        TARGET.write_text(source)
