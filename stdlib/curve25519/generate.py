#!/usr/bin/env python3
"""Regenerate std@1/internal/curve25519_table.hir: the multiples of the edwards25519 base point
that Ed25519's fixed-base multiplication reads, as in ref10's ge_precomp table.

Entry j of position i is (j + 1) * 256^i * B for i in 0..32 and j in 0..8, stored
affine as (y + x, y - x, 2d * x * y), each coordinate fully reduced into five
51-bit limbs, so one position is 8 * 3 * 5 = 120 words."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = HERE.parent / 'std@1' / 'internal' / 'curve25519_table.hir'
P = 2**255 - 19
D = -121665 * pow(121666, P - 2, P) % P

def add(a, b):
    (x1, y1), (x2, y2) = a, b
    t = D * x1 * x2 * y1 * y2 % P
    return ((x1 * y2 + y1 * x2) * pow(1 + t, P - 2, P) % P,
            (y1 * y2 + x1 * x2) * pow(1 - t, P - 2, P) % P)

def base():
    y = 4 * pow(5, P - 2, P) % P
    xx = (y * y - 1) * pow(D * y * y + 1, P - 2, P) % P
    x = pow(xx, (P + 3) // 8, P)
    if (x * x - xx) % P:
        x = x * pow(2, (P - 1) // 4, P) % P
    if x & 1:
        x = P - x
    return x, y

def limbs(v):
    return [(v >> (51 * k)) & (2**51 - 1) for k in range(5)]

def generate():
    out = [
        '// Generated by stdlib/curve25519/generate.py: entry j of BASE_i is (j + 1) * 256^i * B',
        '// on edwards25519, affine as (y + x, y - x, 2dxy) in five 51-bit limbs each.',
    ]
    point = base()
    for i in range(32):
        row, q = [], point
        for j in range(8):
            x, y = q
            row += limbs((y + x) % P) + limbs((y - x) % P) + limbs(2 * D * x * y % P)
            q = add(q, point)
        out.append(f'pub const BASE_{i}: Inline[u64, 120] = [')
        out.append(',\n'.join(f'  {v}' for v in row))
        out.append(']')
        out.append('')
        for _ in range(8):
            point = add(point, point)
    out.append('// The table of position `i` below 32.')
    out.append('@noalloc')
    out.append('pub fn position(i: u64) -> Inline[u64, 120] uses {} {')
    for i in range(31):
        out.append(f'  if i == {i} {{\n    return BASE_{i}\n  }}')
    out.append('  BASE_31')
    out.append('}')
    TARGET.write_text('\n'.join(out) + '\n')

if __name__ == '__main__':
    generate()
