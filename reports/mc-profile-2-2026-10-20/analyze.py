"""Reproduce all M0b projection tables from committed inputs (no timing run)."""
import argparse
import gzip
import hashlib
import importlib.util
import json
from pathlib import Path
import statistics
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def load(name):
    spec = importlib.util.spec_from_file_location(name.replace('-', '_'), ROOT/'tools'/f'{name}.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main(check=False):
    def save(path, contents):
        if check:
            if path.read_text() != contents:
                raise ValueError(f'{path.name} is stale; rerun analyze.py')
        else:
            path.write_text(contents)

    source = (ROOT/'crates/hirsel-rt/src/multicore_policy.rs').read_text()
    policy = {key: int(value.replace('_', '')) for key, value in
              re.findall(r'pub const (AUTO_\w+): u64 = ([0-9_]+);', source)}
    model = load('mc-refinements')
    migration = load('mc-migration')
    strict = load('mc-profile')
    costs = json.loads((HERE/'costs.json').read_text())
    handoff = {w: next(x['ns'] for x in costs['summary']
                       if x['width'] == w and x['variant'] == 'handoff') for w in (4, 8)}
    scenarios = []
    for shape, kind, shared in [('deferrable', 'D', False), ('independent', 'E', False),
                                ('conflicting', 'E', True)]:
        for segment_ns in (50, 200, 500, 1000, 2000, 10000, 100000):
            rows = model.scenario(kind, segment_ns, shared=shared)
            for width in (4, 8):
                values = {mode: model.simulate(rows, width, mode, handoff_ns=round(handoff[width]),
                    run_ahead=policy['AUTO_RUN_AHEAD_OPS'])
                          for mode in ('strict', 'ahead', 'early')}
                base = values['strict']['makespan_ns']
                for mode, v in values.items():
                    v['speedup_vs_strict'] = base/v['makespan_ns']
                    # Histories are validated by small controls; archive counts here.
                    v.pop('publish')
                    v.pop('early_history')
                # A probe measures saved compute and extra role/log overhead.
                candidate = values['early']
                overhead = candidate['early_commits'] * 200 + candidate['logged'] * 20
                saved = max(0, base-candidate['makespan_ns']+overhead)
                probes = sum(r['kind'] != 'H' for r in rows)
                passed = candidate['early_commits'] + candidate['logged']
                auto = (segment_ns >= policy['AUTO_MIN_SEGMENT_NS'] and probes
                        and passed*100 >= probes*policy['AUTO_MIN_PASS_PERCENT']
                        and saved and saved*100 >= overhead*(100+policy['AUTO_GAIN_MARGIN_PERCENT']))
                scenarios.append(dict(shape=shape, segment_ns=segment_ns, width=width,
                    policy='early' if auto else 'strict', probes=probes, eligible=passed,
                    auto_speedup=values['early' if auto else 'strict']['speedup_vs_strict'],
                    results=values))
    historical = []
    for path in sorted((ROOT/'reports/mc-profile-2026-10-20').glob('*.json.gz')):
        samples = json.load(gzip.open(path, 'rt'))
        for width in (4, 8):
            projections = []
            for sample in samples:
                rows = [json.loads(s[3:]) for s in sample['log'].splitlines() if s.startswith('mc ')]
                a, b = strict.simulate(rows, 1), strict.simulate(rows, width)
                projections.append(a['makespan_ns']/b['makespan_ns'])
            historical.append(dict(program=path.name.removesuffix('.json.gz'), width=width,
                strict_speedup=statistics.median(projections),
                refined_speedup=None, reason='M0 has no object footprints; eligibility is unknown'))
    placement = []
    bench_path = HERE/'bench-traces.json.gz'
    if bench_path.exists():
        for trace in json.load(gzip.open(bench_path, 'rt'))['traces']:
            rows = [json.loads(s[3:]) for s in trace['log'].splitlines() if s.startswith('mc ')]
            turns = migration.turns(rows)
            for width in (4, 8):
                placement.append(dict(program=trace['program'], **migration.simulate(turns, width)))
    save(HERE/'results.json', json.dumps(dict(schema=1, policy=policy,
        model_sha256=hashlib.sha256((ROOT/'tools/mc-refinements.py').read_bytes()).hexdigest(),
        placement_sha256=hashlib.sha256((ROOT/'tools/mc-migration.py').read_bytes()).hexdigest(),
        commit_ns=200, log_ns=20, costs=costs['summary'], scenarios=scenarios,
        historical=historical, placement=placement), indent=2)+'\n')
    lines = ['<!-- Generated by analyze.py; model speedups, not measured executor throughput. -->',
             '| Shape | Segment ns | Cores | Run-ahead / strict | Early / strict | Auto / strict | Early ops |',
             '|---|---:|---:|---:|---:|---:|---:|']
    for s in scenarios:
        v = s['results']
        lines.append(f"| {s['shape']} | {s['segment_ns']} | {s['width']} | "
            f"{v['ahead']['speedup_vs_strict']:.3f} | {v['early']['speedup_vs_strict']:.3f} | "
            f"{s['auto_speedup']:.3f} | {v['early']['early_commits']} |")
    lines += ['', '| B1 workload | Cores | Model switches | Migrations | Refresh/switch lower bound |',
              '|---|---:|---:|---:|---:|']
    for p in placement:
        lines.append(f"| {p['program']} | {p['width']} | {p['switches']} | {p['migrations']} | "
                     f"{100*p['migration_per_switch']:.2f}% |")
    lines += ['', '| M0 workload | Cores | Strict speedup vs 1 | Refinements |', '|---|---:|---:|---|']
    for p in historical:
        lines.append(f"| {p['program']} | {p['width']} | {p['strict_speedup']:.3f} | unknown: no footprints |")
    save(HERE/'tables.md', '\n'.join(lines)+'\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    main(parser.parse_args().check)
