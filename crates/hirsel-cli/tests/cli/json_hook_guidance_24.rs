//! Ordinary JSON hook diagnostics retain generated primary spans and source fields.
use std::{fs, path::PathBuf, process::Command};

fn check(source: &str, json: bool) -> (tempfile::TempDir, std::process::Output) {
    let dir = tempfile::tempdir().unwrap();
    fs::write(dir.path().join("relocated.hir"), source).unwrap();
    let stdlib = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../stdlib/std@1/hirsel.json")
        .canonicalize()
        .unwrap();
    let manifest = dir.path().join("hirsel.json");
    fs::write(&manifest,serde_json::json!({"schema":1,"package":{"name":"cli_hooks","version":"0"},"sources":[{"path":"relocated.hir","module":[]}],"dependencies":[{"manifest":stdlib,"package":{"name":"std","version":"1"},"expose":[]}]}).to_string()).unwrap();
    let mut cmd = Command::new(env!("CARGO_BIN_EXE_hirsel"));
    cmd.env("HIRSEL_DAEMON", "off").arg("check");
    if json {
        cmd.arg("--json");
    }
    let output = cmd.arg(manifest).output().unwrap();
    (dir, output)
}

fn checked(encode: bool, hook: &str, rule: &str) {
    let declaration = if encode {
        "fn outer(value: Outer) -> json.Value uses {} = comptime derive.json_value(shape(Outer))"
    } else {
        "fn outer(value: json.Value) -> Result[Outer, String] uses {} = comptime derive.from_json(shape(Outer))"
    };
    let source = format!(
        "// 雪 λ application\ntype Service {{ name: String }}\ntype Outer {{ other: u64, service: List[Option[Service]] }}\n{declaration}\n{hook}\n"
    );
    let (dir, output) = check(&source, true);
    assert_eq!(output.status.code(), Some(1), "{output:?}");
    let diagnostics: Vec<serde_json::Value> = serde_json::Deserializer::from_slice(&output.stdout)
        .into_iter()
        .collect::<Result<_, _>>()
        .unwrap();
    assert_eq!(diagnostics.len(), 1, "{diagnostics:?}");
    let d = &diagnostics[0];
    assert_eq!(d["rule"], rule);
    assert!(
        d["primary"]["file"]
            .as_str()
            .unwrap()
            .contains("<generated:cli_hooks@0/outer>")
    );
    let contract = if encode {
        "fn cli_hooks@0/service_to_json(value: cli_hooks@0/Service) -> std@1/json.Value uses {}"
    } else {
        "fn cli_hooks@0/service_from_json(value: std@1/json.Value) -> core@1/Result[cli_hooks@0/Service, String] uses {}"
    };
    let context = format!("schema field `cli_hooks@0/Outer.service` requires `{contract}`");
    let labels = d["secondary"].as_array().unwrap();
    let field = labels
        .iter()
        .find(|l| l["message"] == context)
        .unwrap_or_else(|| panic!("{d}"));
    let start = source.find("List[Option[Service]]").unwrap();
    assert_eq!(field["span"]["start"], start);
    assert_eq!(field["span"]["end"], start + "List[Option[Service]]".len());
    assert_eq!(field["span"]["line"], 3);
    assert_eq!(field["span"]["column"], 35);
    assert_eq!(
        field["span"]["file"],
        dir.path().join("relocated.hir").to_str().unwrap()
    );
    assert_eq!(
        labels
            .iter()
            .filter(|l| l["message"].as_str().unwrap().starts_with("schema field"))
            .count(),
        1
    );
    let origin = labels
        .iter()
        .find(|l| l["message"] == "generated by this `= comptime` body")
        .unwrap();
    let start = source.find("comptime derive").unwrap();
    assert_eq!(origin["span"]["start"], start);
    assert_eq!(
        origin["span"]["end"],
        source.find("\nfn outer").unwrap() + 1 + declaration.len()
    );
    let (_, human) = check(&source, false);
    assert_eq!(human.status.code(), Some(1));
    let human = format!(
        "{}{}",
        String::from_utf8_lossy(&human.stdout),
        String::from_utf8_lossy(&human.stderr)
    );
    assert!(human.contains(rule), "{human}");
    for label in labels {
        assert!(
            human.contains(label["message"].as_str().unwrap()),
            "{human}"
        );
    }
    assert!(d["fix"].is_null());
}

#[test]
fn json_hook_guidance_24_text_json_missing_both_directions() {
    for encode in [true, false] {
        checked(encode, "", "LANG-4");
    }
}

#[test]
fn json_hook_guidance_24_text_json_wrong_contracts() {
    checked(
        true,
        "fn service_to_json(value: u64) -> json.Value uses {} { Null }",
        "LANG-7",
    );
    checked(
        true,
        "fn service_to_json(value: Service) -> String uses {} { \"wrong\" }",
        "LANG-7",
    );

    checked(
        false,
        "fn service_from_json(value: json.Value) -> Result[u64,String] uses {} { Ok(0u64) }",
        "LANG-7",
    );
    checked(
        true,
        "fn service_to_json(take value: Service) -> json.Value uses {} { Null }",
        "OWN-2",
    );
}

#[test]
fn json_hook_guidance_24_malformed_comments_keep_verdict() {
    for comments in [
        "",
        "// schema-hook malformed\n// schema-contract ignored\n",
        "// schema-hook cli_hooks@0/Outer\tunknown\n// schema-contract misleading\n",
        "// schema-hook cli_hooks@0/Outer\tservice\n// broken-contract ignored\n",
    ] {
        let source = format!(
            r##"type Service {{ name: String }}
type Outer {{ service: Service }}
fn generate() -> Result[Body[fn(Outer) -> json.Value uses {{}}], String] uses {{}} {{
  Ok(codegen.body(r#"fn(value: cli_hooks@0/Outer) -> std@1/json.Value uses {{}} {{
{comments}let convert = fn(input: cli_hooks@0/Service) -> std@1/json.Value uses {{}} {{ cli_hooks@0/missing(input) }}
convert(value.service)
}}"#))
}}
fn outer(value: Outer) -> json.Value uses {{}} = comptime generate()
"##
        );
        let (_, output) = check(&source, true);
        assert_eq!(output.status.code(), Some(1), "{output:?}");
        let d: serde_json::Value = serde_json::from_slice(&output.stdout).unwrap();
        assert_eq!(d["rule"], "LANG-4");
        assert!(
            d["message"]
                .as_str()
                .unwrap()
                .contains("cli_hooks@0/missing")
        );
        assert!(
            !d["secondary"]
                .as_array()
                .unwrap()
                .iter()
                .any(|l| l["message"].as_str().unwrap().starts_with("schema field"))
        );
    }
}
