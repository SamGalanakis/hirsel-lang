//! CLI text/JSON agree on generated offsets and original UTF-8 field sites.
use std::{fs, path::PathBuf, process::Command};

fn checked(direction: &str, wrong: &str) {
    let root = tempfile::tempdir().unwrap();
    let stdlib = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../stdlib/std@1/hirsel.json")
        .canonicalize()
        .unwrap();
    let (input, output) = if direction == "decode" {
        ("json.Value", "Outer")
    } else {
        ("Outer", "json.Value")
    };
    let mut source = format!(
        "// λ application\ntype Service {{ name: String }}\ntype Outer {{ service: Service }}\nfn outer(value: {input}, mut check: schema.CheckState) -> Result[unique {output}, schema.SchemaError] uses {{}} = comptime derive.schema_{direction}(shape(Outer), schema.strict_policy())\n"
    );
    if wrong == "result" {
        source.push_str("fn service_schema_encode(value: Service, mut check: schema.CheckState) -> Result[unique String, schema.SchemaError] uses {} { Ok(\"wrong\") }\n");
    }
    if wrong == "mode" {
        source.push_str("fn service_schema_encode(value: Service, take check: schema.CheckState) -> Result[unique json.Value, schema.SchemaError] uses {} { Ok(Text(\"x\")) }\n");
    }
    let rule = match wrong {
        "result" => "LANG-7",
        "mode" => "OWN-2",
        _ => "LANG-4",
    };
    fs::write(root.path().join("relocated.hir"), &source).unwrap();
    let manifest = root.path().join("hirsel.json");
    fs::write(&manifest, serde_json::json!({"schema":1,"package":{"name":"cli_hooks","version":"0"},"sources":[{"path":"relocated.hir","module":[]}],"dependencies":[{"manifest":stdlib,"package":{"name":"std","version":"1"},"expose":[]}]}).to_string()).unwrap();
    let run = |json| {
        let mut cmd = Command::new(env!("CARGO_BIN_EXE_hirsel"));
        cmd.env("HIRSEL_DAEMON", "off").arg("check");
        if json {
            cmd.arg("--json");
        }
        let output = cmd.arg(&manifest).output().unwrap();
        assert_eq!(output.status.code(), Some(1), "{output:?}");
        output
    };
    let json = run(true);
    let diagnostics: Vec<serde_json::Value> = serde_json::Deserializer::from_slice(&json.stdout)
        .into_iter()
        .collect::<Result<_, _>>()
        .unwrap();
    assert_eq!(diagnostics.len(), 1, "{diagnostics:?}");
    let d = &diagnostics[0];
    assert_eq!(d["rule"], rule);
    assert!(
        d["primary"]["file"]
            .as_str()
            .unwrap()
            .contains("<generated:cli_hooks@0/outer>")
    );
    let callee = format!("cli_hooks@0/service_schema_{direction}");
    if wrong.is_empty() {
        assert_eq!(
            d["primary"]["end"].as_u64().unwrap() - d["primary"]["start"].as_u64().unwrap(),
            callee.len() as u64
        );
    }
    let fields = d["secondary"].as_array().unwrap();
    let field = fields
        .iter()
        .find(|l| {
            l["message"]
                .as_str()
                .unwrap()
                .starts_with("schema field `cli_hooks@0/Outer.service` requires")
        })
        .unwrap_or_else(|| panic!("{d}"));
    let start = source.find("service: Service").unwrap() + "service: ".len();
    assert_eq!(field["span"]["start"], start);
    assert_eq!(field["span"]["end"], start + "Service".len());
    assert!(
        field["span"]["file"]
            .as_str()
            .unwrap()
            .ends_with("/relocated.hir")
    );
    assert_eq!(field["span"]["line"], 3);
    assert_eq!(field["span"]["column"], 23);
    let message = field["message"].as_str().unwrap();
    assert!(message.contains(&callee));
    assert!(message.contains("mut check: std@1/schema.CheckState"));
    assert!(message.contains("core@1/Result[unique "));
    assert!(message.ends_with("uses {}`"));
    let origin = fields
        .iter()
        .find(|l| l["message"] == "generated by this `= comptime` body")
        .unwrap();
    let start = source.find("comptime derive").unwrap();
    assert_eq!(origin["span"]["start"], start);
    assert_eq!(
        origin["span"]["end"],
        source.trim_end().find("schema.strict_policy())").unwrap()
            + "schema.strict_policy())".len()
    );
    let human = run(false);
    let human = format!(
        "{}{}",
        String::from_utf8_lossy(&human.stdout),
        String::from_utf8_lossy(&human.stderr)
    );
    for label in fields {
        assert!(
            human.contains(label["message"].as_str().unwrap()),
            "{human}"
        );
    }
    assert!(human.contains(rule));
    assert_eq!(json.stdout, run(true).stdout);
    assert!(d["fix"].is_null());
}

#[test]
fn schema_hook_diagnostics_17_text_json_missing_decode_encode() {
    for direction in ["decode", "encode"] {
        checked(direction, "");
    }
}

#[test]
fn schema_hook_diagnostics_17_text_json_wrong_result() {
    checked("encode", "result");
}

#[test]
fn schema_hook_diagnostics_17_text_json_wrong_mode() {
    checked("encode", "mode");
}
