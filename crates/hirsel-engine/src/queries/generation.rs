//! CT-5 typed generation. A function whose body is `= comptime e` gets the body
//! its generator returns. `e` is checked and evaluated as the private constant
//! `name$generator: core@1/Result[core@1/Body[F], core@1/String]`, where `F` is
//! the header's own function type, so ordinary checking rejects a mismatched
//! header before evaluation. The generated text, one function literal, becomes
//! its own source file: the literal is normalized like a header and compared
//! with the declared one, and its body follows the written header in one token
//! tape that is parsed, resolved and checked like a written body.
use super::*;
use hirsel_syntax::{
    ExprId, ExprKind, FunctionSyntax, Keyword, PackageId, Path, TokenKind, TypeArgument, TypeExpr,
    TypeExprId, TypeExprKind, Visibility,
};
use hirsel_types::SignatureKind;

/// A declaration's generated source, for diagnostics and `hirsel expand`.
#[derive(Clone, Debug)]
pub struct GeneratedSource {
    pub file: FileId,
    pub text: String,
    /// The `comptime e` body that generated it.
    pub site: Span,
}

/// The `comptime e` body of a generated declaration.
pub(crate) fn generator(file: &SyntaxFile, item: ItemId) -> Option<ExprId> {
    match file.tree.items[item.0 as usize].kind {
        ItemKind::Function {
            body: Some(body), ..
        } if matches!(
            file.tree.expressions[body.0 as usize].kind,
            ExprKind::Comptime(_)
        ) =>
        {
            Some(body)
        }
        _ => None,
    }
}

fn renamed(definition: &DefPath, suffix: &str) -> DefPath {
    let mut path = definition.clone();
    path.0.name = format!("{}${suffix}", path.0.name);
    path
}

fn diagnostic(rule: &'static str, span: Span, message: impl Into<String>) -> QueryError {
    QueryError::Diagnostics(vec![Diagnostic::error(
        hirsel_diag::RuleId::new(rule).expect("rule id"),
        span,
        message,
    )])
}

/// Every primary site in generated text also marks the declaration that generated it.
fn label(mut error: QueryError, generated: FileId, site: Span) -> QueryError {
    if let QueryError::Diagnostics(diagnostics) = &mut error {
        for d in diagnostics {
            if d.primary.file == generated {
                d.secondary.push(hirsel_diag::Label {
                    span: site,
                    message: "generated by this `= comptime` body".into(),
                });
            }
        }
    }
    error
}

/// The phase reads of one generated check, accumulated across its steps.
struct Reads {
    reads: DependencyReads,
    representations: BTreeMap<DefPath, ContentHash>,
}

impl QueryEngine {
    /// The source generated for `definition`, once its check has run.
    pub fn generated_source(&self, definition: &DefPath) -> Option<&GeneratedSource> {
        self.generated.get(definition)
    }

    /// Every generated body produced so far, by declaration.
    pub fn generated_sources(&self) -> impl Iterator<Item = (&DefPath, &GeneratedSource)> {
        self.generated.iter()
    }

    /// Run `step` with a recorder for `owner`, keeping its reads.
    fn recorded<T>(
        &mut self,
        owner: &DefPath,
        reads: &mut Reads,
        step: impl FnOnce(&mut Recorder<'_>) -> Result<T, QueryError>,
    ) -> Result<T, QueryError> {
        let mut recorder = Recorder {
            owner: owner.clone(),
            private_shapes: true,
            representations: std::mem::take(&mut reads.representations),
            engine: self,
            reads: std::mem::take(&mut reads.reads),
        };
        let result = step(&mut recorder);
        reads.representations = recorder.representations;
        reads.reads = recorder.reads;
        result
    }

    /// check_query for a generated declaration: the generated body's checked
    /// artifact, cached under the implementations its generator executed.
    pub(super) fn generated_check_query(
        &mut self,
        definition: &DefPath,
        snapshot: ItemSnapshot,
        body: ExprId,
    ) -> Result<Arc<QueryOutput<TypedBody>>, QueryError> {
        let site = snapshot.file.tree.expressions[body.0 as usize].origin.span;
        // CT-4: a generator that needs its own declaration's body.
        if self
            .comptime_stack
            .iter()
            .any(|(path, _)| path == definition)
        {
            return Err(diagnostic(
                "CT-4",
                site,
                "compile-time dependency cycle: this generator runs its own declaration",
            ));
        }
        let signature = self.signature_output(definition)?;
        let key = self.key(definition, QueryKind::Check)?;
        if let Some(cached) = self.checked.get(definition).cloned()
            && self.valid(&cached, &key)
        {
            self.inherit_execution(&cached.executed);
            return cached.result.clone();
        }
        let mut reads = Reads {
            reads: DependencyReads::default(),
            representations: BTreeMap::new(),
        };
        reads
            .reads
            .signatures
            .extend(signature.dependencies.clone());
        reads.reads.signatures.push(SignatureDependency {
            definition: definition.clone(),
            fingerprint: signature.value.fingerprint,
        });
        self.start(definition, QueryKind::Check)?;
        self.comptime_stack.push((definition.clone(), site));
        self.execution_stack.push(ExecutionReads::default());
        let result = self.generate(definition, &snapshot, body, &signature.value, &mut reads);
        let executed = self
            .execution_stack
            .pop()
            .expect("generation execution frame");
        self.comptime_stack.pop();
        let mut cached = self.finish(key, reads.reads, result, reads.representations);
        Arc::make_mut(&mut cached).executed = executed;
        if !cached.result.as_ref().is_err_and(|e| !e.cacheable()) {
            self.checked.insert(definition.clone(), cached.clone());
        }
        cached.result.clone()
    }

    fn generate(
        &mut self,
        definition: &DefPath,
        snapshot: &ItemSnapshot,
        body: ExprId,
        signature: &Signature,
        reads: &mut Reads,
    ) -> Result<QueryOutput<TypedBody>, QueryError> {
        let site = snapshot.file.tree.expressions[body.0 as usize].origin.span;
        let SignatureKind::Function(declared) = &signature.kind else {
            return Err(QueryError::NotImplemented);
        };
        if !declared.generics.is_empty() {
            return Err(diagnostic(
                "CT-2",
                site,
                "a generated declaration is not generic: generic shape inputs are outside the closed compile-time frame",
            ));
        }
        let text = self.generated_text(definition, snapshot, body, reads)?;
        let file = match self.generated.get(definition) {
            Some(g) if g.text == text => g.file,
            _ => {
                let origin = self.sources.file(site.file).unwrap().path.display();
                let path = format!("{origin}#{definition}");
                let file = self.sources.add(path, text.clone()).ok_or_else(|| {
                    QueryError::Operational(hirsel_types::OperationalFailure {
                        operation: "typed generation".into(),
                        message: "generated source exceeds the source map".into(),
                    })
                })?;
                self.generated.insert(
                    definition.clone(),
                    GeneratedSource {
                        file,
                        text: text.clone(),
                        site,
                    },
                );
                file
            }
        };
        self.generated_body(definition, snapshot, body, signature, file, reads)
            .map_err(|e| label(e, file, site))
            .map(|mut output| {
                for d in &mut output.diagnostics {
                    if d.primary.file == file {
                        d.secondary.push(hirsel_diag::Label {
                            span: site,
                            message: "generated by this `= comptime` body".into(),
                        });
                    }
                }
                output
            })
    }

    /// Check and evaluate the generator as a private constant of type
    /// `Result[Body[F], String]`; its text, or CT-1 for its `Error`.
    fn generated_text(
        &mut self,
        definition: &DefPath,
        snapshot: &ItemSnapshot,
        body: ExprId,
        reads: &mut Reads,
    ) -> Result<String, QueryError> {
        let source = &snapshot.file.tree.items[snapshot.item.0 as usize];
        let ItemKind::Function { signature, .. } = &source.kind else {
            return Err(QueryError::NotImplemented);
        };
        let ExprKind::Comptime(value) = snapshot.file.tree.expressions[body.0 as usize].kind else {
            return Err(QueryError::NotImplemented);
        };
        let site = snapshot.file.tree.expressions[body.0 as usize].origin;
        let helper = renamed(definition, "generator");
        let mut file = (*snapshot.file).clone();
        let core = |name: &str, symbols: &mut Interner| Path {
            package: Some(PackageId {
                name: "core".into(),
                version: "1".into(),
            }),
            segments: vec![symbols.intern(name)],
        };
        let mut push = |kind: TypeExprKind, tree: &mut hirsel_syntax::SyntaxTree| {
            tree.types.push(TypeExpr { origin: site, kind });
            TypeExprId(tree.types.len() as u32 - 1)
        };
        // F: the header's parameters with their passing modes, result and `uses`.
        let function = push(
            TypeExprKind::Function(FunctionSyntax {
                parameters: signature.parameters.clone(),
                result: signature.result,
                uses: signature.uses.clone(),
                ..Default::default()
            }),
            &mut file.tree,
        );
        let body_type = push(
            TypeExprKind::Named {
                path: core("Body", &mut self.symbols),
                arguments: vec![TypeArgument::Type(function)],
            },
            &mut file.tree,
        );
        let string = push(
            TypeExprKind::Named {
                path: core("String", &mut self.symbols),
                arguments: vec![],
            },
            &mut file.tree,
        );
        let ty = push(
            TypeExprKind::Named {
                path: core("Result", &mut self.symbols),
                arguments: vec![TypeArgument::Type(body_type), TypeArgument::Type(string)],
            },
            &mut file.tree,
        );
        let mut item = source.clone();
        item.name = self.symbols.intern(&helper.0.name);
        file.symbols = Arc::new(self.symbols.clone());
        item.definition = helper.clone();
        item.visibility = Visibility::Private;
        item.attributes.clear();
        item.kind = ItemKind::Const { ty, value };
        let id = ItemId(file.tree.items.len() as u32);
        file.tree.items.push(item);
        let file = Arc::new(file);
        let symbols = self.symbols.clone();
        let adapters = (
            self.adapters.signature.clone(),
            self.adapters.resolver.clone(),
            self.adapters.checker.clone(),
            self.adapters.modes.clone(),
        );
        let (Some(signer), Some(resolver), Some(checker), Some(modes)) = adapters else {
            return Err(QueryError::NotImplemented);
        };
        let constant = self.recorded(definition, reads, |r| {
            signer.signature(file.clone(), id, &symbols, r)
        })?;
        if has_errors(&constant.diagnostics) {
            return Err(QueryError::Diagnostics(constant.diagnostics));
        }
        let mut constant = constant.value;
        constant.fingerprint =
            hirsel_types::encoding::fingerprint(&constant, &[]).map_err(|e| {
                QueryError::Operational(hirsel_types::OperationalFailure {
                    operation: "typed generation".into(),
                    message: format!("generator signature: {e:?}"),
                })
            })?;
        let resolution = self.recorded(definition, reads, |r| {
            resolver.resolve(file.clone(), id, &symbols, r)
        })?;
        if has_errors(&resolution.diagnostics) {
            // `e` is a closed frame, like an inline comptime: naming a declared parameter
            // reads a run-time value, which is CT-2, not an unknown name.
            let mut diagnostics = resolution.diagnostics;
            for d in &mut diagnostics {
                let parameter = signature
                    .parameters
                    .iter()
                    .filter_map(|p| self.symbols.resolve(p.name?))
                    .find(|name| {
                        d.rule.as_str() == "LANG-4"
                            && d.message == format!("unresolved name `{name}`")
                    });
                if let Some(name) = parameter {
                    *d = Diagnostic::error(
                        const { hirsel_diag::RuleId::of("CT-2") },
                        d.primary,
                        format!(
                            "a generator reads no parameter: `{name}` is a run-time value of the \
                             generated function"
                        ),
                    );
                }
            }
            return Err(QueryError::Diagnostics(diagnostics));
        }
        let typed = self.recorded(definition, reads, |r| {
            checker.check(file.clone(), id, resolution.value, &constant, r)
        })?;
        if has_errors(&typed.diagnostics) {
            return Err(QueryError::Diagnostics(typed.diagnostics));
        }
        let analyzed = self.recorded(definition, reads, |r| {
            modes.check_modes(typed.value, &constant, r)
        })?;
        if has_errors(&analyzed.diagnostics) {
            return Err(QueryError::Diagnostics(analyzed.diagnostics));
        }
        let analyzed = analyzed.value;
        let SignatureKind::Const { ty, .. } = constant.kind else {
            return Err(QueryError::NotImplemented);
        };
        let ty = analyzed
            .typed
            .checked
            .expressions
            .iter()
            .find(|r| r.expression == value)
            .map_or(ty, |r| r.ty);
        self.prepare_materialization_environment();
        let constants = self.prepare_values(&analyzed, &constant)?;
        let (result, _, _) =
            self.run_evaluation(&analyzed, &constant, value, value, ty, &constants, &[])?;
        let site = site.span;
        let unexpected = || {
            QueryError::Operational(hirsel_types::OperationalFailure {
                operation: "typed generation".into(),
                message: "generator returned no Result[Body, String]".into(),
            })
        };
        let hirsel_interp::Value::Variant { variant, fields } = result else {
            return Err(unexpected());
        };
        let Some(Some(hirsel_interp::Value::String(text))) = fields.into_iter().next() else {
            return Err(unexpected());
        };
        match variant {
            0 => Ok(text),
            _ => {
                let mut d = Diagnostic::error(
                    const { hirsel_diag::RuleId::of("CT-1") },
                    site,
                    "the generator returned an error",
                );
                d.notes.push(text);
                Err(QueryError::Diagnostics(vec![d]))
            }
        }
    }

    /// Parse the generated function literal, compare its type with the header,
    /// and check its body after the written header.
    fn generated_body(
        &mut self,
        definition: &DefPath,
        snapshot: &ItemSnapshot,
        body: ExprId,
        signature: &Signature,
        generated: FileId,
        reads: &mut Reads,
    ) -> Result<QueryOutput<TypedBody>, QueryError> {
        let source = &snapshot.file.tree.items[snapshot.item.0 as usize];
        let context = FileContext {
            package: definition.0.package.clone(),
            modules: definition.0.modules.clone(),
        };
        let (Some(lexer), Some(parser), Some(signer), Some(resolver), Some(checker)) = (
            self.adapters.lexer.clone(),
            self.adapters.parser.clone(),
            self.adapters.signature.clone(),
            self.adapters.resolver.clone(),
            self.adapters.checker.clone(),
        ) else {
            return Err(QueryError::NotImplemented);
        };
        let lexed = lexer.lex(generated, &self.sources, &mut self.symbols)?;
        if has_errors(&lexed.diagnostics) {
            return Err(QueryError::Diagnostics(lexed.diagnostics));
        }
        let tokens = lexed.value;
        let significant = |t: &hirsel_syntax::Token| !matches!(t.kind, TokenKind::Trivia(_));
        let first = tokens.iter().position(significant);
        let Some(fn_index) = first.filter(|&i| tokens[i].kind == TokenKind::Keyword(Keyword::Fn))
        else {
            let span = first.map_or(
                Span {
                    file: generated,
                    start: 0,
                    end: 0,
                },
                |i| tokens[i].span,
            );
            return Err(diagnostic(
                "CT-5",
                span,
                "generated text is not one function literal `fn(..) .. { .. }`",
            ));
        };
        // The literal as a declaration: `fn <declared name>(..) .. { .. }`.
        let name = snapshot
            .file
            .tokens
            .iter()
            .find(|t| t.span == source.name_span);
        let Some(name) = name.cloned() else {
            return Err(QueryError::NotImplemented);
        };
        let mut tape = tokens[..=fn_index].to_vec();
        tape.push(name);
        tape.extend_from_slice(&tokens[fn_index + 1..]);
        let symbols = self.symbols.clone();
        let parsed = parser.parse(generated, tape, &context, &self.sources, &symbols)?;
        if has_errors(&parsed.diagnostics) {
            return Err(QueryError::Diagnostics(parsed.diagnostics));
        }
        let mut literal = parsed.value;
        let literal_item = match literal.roots[..] {
            [id] => id,
            _ => {
                return Err(diagnostic(
                    "CT-5",
                    tokens[fn_index].span,
                    "generated text is not one function literal `fn(..) .. { .. }`",
                ));
            }
        };
        let (literal_signature, literal_body) =
            match &literal.tree.items[literal_item.0 as usize].kind {
                ItemKind::Function {
                    signature,
                    body: Some(body),
                    abi: None,
                } if literal.tree.items[literal_item.0 as usize]
                    .attributes
                    .is_empty() =>
                {
                    (signature.clone(), *body)
                }
                _ => {
                    return Err(diagnostic(
                        "CT-5",
                        tokens[fn_index].span,
                        "generated text is not one function literal `fn(..) .. { .. }`",
                    ));
                }
            };
        let literal_origin = literal.tree.items[literal_item.0 as usize].origin;
        let body_start = literal.tree.expressions[literal_body.0 as usize]
            .origin
            .tokens
            .start as usize;
        let header_span = Span {
            file: generated,
            start: tokens[fn_index].span.start,
            end: literal.tokens[body_start].span.start,
        };
        literal.tree.items[literal_item.0 as usize].definition = renamed(definition, "literal");
        let literal = Arc::new(literal);
        let normalized = self.recorded(definition, reads, |r| {
            signer.signature(literal.clone(), literal_item, &symbols, r)
        })?;
        if has_errors(&normalized.diagnostics) {
            return Err(QueryError::Diagnostics(normalized.diagnostics));
        }
        if !same_function(signature, &normalized.value) {
            return Err(diagnostic(
                "LANG-7",
                header_span,
                "the generated function literal's type differs from the declared header",
            ));
        }
        let parameters: Vec<_> = literal_signature
            .parameters
            .iter()
            .filter_map(|p| {
                let span = literal
                    .parameter_name_span(literal_origin, p)
                    .unwrap_or(header_span);
                Some((p.name?, span))
            })
            .collect();
        // The written header up to its `=`, then the literal's body: one item.
        let written = &snapshot.file.tokens;
        let start = source.origin.tokens.start as usize;
        // The body's `comptime` token, after the `=` that ends the header.
        let mut end = snapshot.file.tree.expressions[body.0 as usize]
            .origin
            .tokens
            .start as usize;
        let mut equals = false;
        while end > start && !(equals && significant(&written[end - 1])) {
            equals |= significant(&written[end - 1]);
            end -= 1;
        }
        let mut tape: Vec<_> = written[start..end].to_vec();
        // literal token i >= fn_index + 2 is generated token i - 1.
        tape.extend_from_slice(&tokens[body_start - 1..]);
        let parsed = parser.parse(snapshot.file.file, tape, &context, &self.sources, &symbols)?;
        if has_errors(&parsed.diagnostics) {
            return Err(QueryError::Diagnostics(parsed.diagnostics));
        }
        let mut file = parsed.value;
        let id = match file.roots[..] {
            [id] => id,
            _ => return Err(QueryError::NotImplemented),
        };
        {
            let item = &mut file.tree.items[id.0 as usize];
            item.origin.span = source.origin.span;
            item.text_hash = ContentHash::of_parts(
                "hirsel.generated-item.v1",
                [
                    source.text_hash.0.as_slice(),
                    self.generated[definition].text.as_bytes(),
                ],
            );
            item.generated = Some(parameters);
        }
        let file = Arc::new(file);
        let resolution = self.recorded(definition, reads, |r| {
            resolver.resolve(file.clone(), id, &symbols, r)
        })?;
        if has_errors(&resolution.diagnostics) {
            return Err(QueryError::Diagnostics(resolution.diagnostics));
        }
        self.recorded(definition, reads, |r| {
            checker.check(file.clone(), id, resolution.value, signature, r)
        })
    }
}

/// Whether a literal's normalized header has the declared function type:
/// passing modes, parameter types, result and `uses`. Names, labels,
/// attributes and contracts belong to the declaration.
fn same_function(declared: &Signature, literal: &Signature) -> bool {
    let (SignatureKind::Function(d), SignatureKind::Function(l)) = (&declared.kind, &literal.kind)
    else {
        return false;
    };
    let equal =
        |a, b| hirsel_types::semantic_equal(&declared.types, a, &literal.types, b) == Ok(true);
    d.parameters.len() == l.parameters.len()
        && d.parameters
            .iter()
            .zip(l.parameters.iter())
            .all(|(a, b)| a.passing == b.passing && equal(a.ty, b.ty))
        && equal(d.result, l.result)
        && d.uses == l.uses
}
