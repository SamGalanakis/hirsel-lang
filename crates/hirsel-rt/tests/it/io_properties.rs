//! Every runtime request has an explicit cancellation classification. The interpreter-checked
//! properties are in hirsel-pipeline-tests (`rt_io_properties`).
use hirsel_rt::io::*;

#[test]
fn every_request_has_an_explicit_cancellation_classification() {
    struct Classification;
    impl Adapter for Classification {
        fn preflight(&self, _: &Request) -> Result<Option<Completion>, AdapterError> {
            Ok(Some(Completion::Ready))
        }
        fn call(&mut self, request: Request) -> Result<Completion, AdapterError> {
            assert!(
                matches!(request, Request::Close { .. }),
                "unexpected effect: {request:?}"
            );
            Ok(Completion::Unit(Ok(())))
        }
    }
    for request in super::tape_property::requests(0) {
        let cancellable = match &request {
            Request::ProcessTime { .. } | Request::ProcessSettle { .. } => false,
            Request::Stdin { .. } => false,
            Request::Stderr { .. } => false,
            Request::ReadStdin { .. } => true,
            Request::PrintStderr { .. } => true,
            Request::EnvGet { .. } => false,
            Request::EnvNarrow { .. } => false,
            Request::MonotonicClock { .. } => false,
            Request::WallClock { .. } => false,
            Request::Monotonic { .. } => false,
            Request::Wall { .. } => false,
            Request::Random { .. } => false,
            Request::RandomBytes { .. } => false,
            // Telemetry capture is never a cancellation point (CONC-3).
            Request::Telemetry { .. } => false,
            Request::TelemetryBegin { .. } => false,
            Request::TelemetryEvent { .. } => false,
            Request::TelemetryFinish { .. } => false,
            Request::TelemetryLog { .. } => false,
            Request::TelemetryMeasure { .. } => false,
            Request::SleepUntil { .. } => true,
            Request::Signals { .. } => false,
            Request::SignalWait { .. } => true,
            Request::Tasks { .. } => false,
            Request::Net { .. } => false,
            Request::Process { .. } => false,
            Request::TestProcess { .. } => false,
            Request::ProcessNarrow { .. } => false,
            Request::ProcessRun { .. } => true,
            Request::ProcessPipeline { .. } => true,
            Request::ProcessSpawn { .. } => true,
            Request::ProcessSpawnPipeline { .. } => true,
            Request::ChildWrite { .. } => true,
            Request::ChildCloseStdin { .. } => false,
            Request::ChildRead { .. } => true,
            Request::ChildWait { .. } => true,
            Request::ChildKill { .. } => false,
            Request::GroupWait { .. } => true,
            Request::TestCheck { .. } => false,
            Request::TestCheckCase { .. } => false,
            Request::TestFail { .. } => false,
            Request::TestClock { .. } => false,
            Request::TestSeed { .. } => false,
            Request::TestTasks { .. } => false,
            Request::TestLog { .. } => false,
            Request::TestSnapshot { .. } => false,
            Request::TestNet { .. } => false,
            Request::TestDir { .. } => false,
            Request::Stdout { .. } => false,
            Request::Directory { .. } => false,
            Request::NarrowDir { .. } => false,
            Request::ReadOnlyDir { .. } => false,
            Request::Print { .. } => true,
            Request::Open { .. } => true,
            Request::Create { .. } => true,
            Request::OpenAppend { .. } => true,
            Request::FileRead { .. } => true,
            Request::FileSeek { .. } => true,
            Request::FileWrite { .. } => true,
            Request::FileAppend { .. } => true,
            Request::NarrowFile { .. } => false,
            Request::ReadDirPage { .. } => true,
            Request::Metadata { .. } => true,
            Request::Mkdir { .. } => true,
            Request::Rename { .. } => true,
            Request::RemoveDir { .. } => true,
            Request::SetPermissions { .. } => true,
            Request::RemoveAll { .. } => true,
            Request::Size { .. } => true,
            Request::Read { .. } => true,
            Request::Write { .. } => true,
            Request::Remove { .. } => true,
            Request::CreateAtomic { .. } => true,
            Request::WriteAll { .. } => true,
            Request::Commit { .. } => true,
            Request::Sync { .. } => true,
            Request::PutNew { .. } => true,
            Request::Map { .. } => true,
            Request::MapView { .. } => false,
            Request::MapCheck { .. } => false,
            Request::Watch { .. } => true,
            Request::WatchNext { .. } => true,
            Request::TestDirEvent { .. } => false,
            Request::TestCrash { .. } => false,
            Request::Close { .. } => false,
            Request::NetNarrow { .. } => false,
            Request::Resolve { .. } => true,
            Request::Connect { .. } => true,
            Request::UdpBind { .. } => true,
            Request::UdpSend { .. } => true,
            Request::UdpRecv { .. } => true,
            Request::ConnectAddr { .. } => true,
            Request::NetRead { .. } => true,
            Request::NetWrite { .. } => true,
            Request::NetWriteAll { .. } => true,
            Request::Shutdown { .. } => false,
            Request::SetTimeout { .. } => false,
            Request::PeerAddr { .. } => false,
            Request::NetSplit { .. } => false,
            Request::NetJoin { .. } => false,
            Request::TlsConnect { .. } => true,
            Request::TlsAccept { .. } => true,
            Request::TlsPeer { .. } => false,
            Request::TlsProtocol { .. } => false,
            Request::TlsClose { .. } => true,
            Request::Listen { .. } => false,
            Request::Accept { .. } => true,
            Request::LocalAddr { .. } => false,
            Request::UnixConnect { .. } => true,
            Request::UnixListen { .. } => false,
            // A runner call is committed once sent; RUN-9 forwards its cancellation.
            Request::RunnerCall(_) => false,
            Request::RunnerPoll { .. } => false,
            Request::RunnerCancel { .. } => false,
            Request::CallReturn(_) => false,
            Request::Stopped => false,
            Request::Ready { .. } => false,
            Request::Schedule { .. } | Request::CpuControl { .. } => false,
        };
        assert_eq!(
            hirsel_rt::io_checks::cancel(&mut Classification, &request, 3).unwrap(),
            cancellable.then_some(Completion::Ready),
            "{request:?}"
        );
    }
}
