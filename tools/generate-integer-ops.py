#!/usr/bin/env python3
"""Generate the ten concrete integer arithmetic/radix modules.

Hirsel has no source integer-width trait. One template defines every width's
policy; shared radix parsing/formatting lives in std@1/internal.integer.
Run with --check to verify that checked-in sources match the template.
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'stdlib/std@1'

TEMPLATE = '''// Generated by tools/generate-integer-ops.py; edit the template there.
// Rust core/src/num/{int_macros,uint_macros}.rs arithmetic policies, f6c1107f.
@noalloc
pub fn checked_add(a: $T, b: $T) -> Option[$T] uses {} {
  core@1/int.checked_add(a, b)
}

@noalloc
pub fn saturating_add(a: $T, b: $T) -> $T uses {} {
  core@1/int.saturating_add(a, b)
}

@noalloc
pub fn wrapping_add(a: $T, b: $T) -> $T uses {} {
  core@1/int.wrapping_add(a, b)
}

@noalloc
pub fn checked_sub(a: $T, b: $T) -> Option[$T] uses {} {
  if $SUB_OVERFLOW { None } else { Some(a - b) }
}

@noalloc
pub fn checked_mul(a: $T, b: $T) -> Option[$T] uses {} {
$MUL_CHECK
  Some(a * b)
}

@noalloc
pub fn saturating_sub(a: $T, b: $T) -> $T uses {} {
  match checked_sub(a, b) {
    Some(value) => value,
    None => $SUB_CLAMP,
  }
}

@noalloc
pub fn saturating_mul(a: $T, b: $T) -> $T uses {} {
  match checked_mul(a, b) {
    Some(value) => value,
    None => $MUL_CLAMP,
  }
}

@noalloc
pub fn wrapping_sub(a: $T, b: $T) -> $T uses {} {
  core@1/int.wrapping_add(a, core@1/int.wrapping_add(~b, 1))
}

@noalloc
pub fn wrapping_mul(a: $T, b: $T) -> $T uses {} {
$WRAPPING_MUL
}

@noalloc
pub fn parse_radix(text: String, radix: u8) -> Result[$T, scalar.ParseError] uses {} {
  match internal.integer.read_radix(text, radix, $SIGNED, $MAXu128, $NEG_LIMITu128) {
    Error(error) => Error(error),
    Ok((magnitude, negative)) => {
$PARSE_VALUE
      Ok(value)
    },
  }
}

pub fn format_radix(value: $T, radix: u8) -> Result[unique String, scalar.ParseError] uses {} {
$FORMAT_MAGNITUDE
  internal.integer.format_radix(magnitude, $NEGATIVE, radix)
}
'''


def module_text(signed, width):
    t = ('i' if signed else 'u') + str(width)
    maximum = (1 << (width - int(signed))) - 1
    minimum = -(1 << (width - 1)) if signed else 0
    fields = {
        'T': t,
        'SIGNED': str(signed).lower(),
        'MAX': str(maximum),
        'NEG_LIMIT': str(-minimum),
    }
    if width < 128:
        wide = ('i' if signed else 'u') + str(width * 2)
        fields['WRAPPING_MUL'] = f'''  let wide_a: {wide} = core@1/int.widen(a)
  let wide_b: {wide} = core@1/int.widen(b)
  core@1/int.truncate(wide_a * wide_b)'''
    else:
        # A = a0 + 2^64*a1, B = b0 + 2^64*b1. The a1*b1 term
        # vanishes modulo 2^128; each remaining limb product fits u128.
        fields['WRAPPING_MUL'] = '''  let left: u128 = core@1/int.truncate(a)
  let right: u128 = core@1/int.truncate(b)
  let low_left = left & 0xffffffffffffffffu128
  let low_right = right & 0xffffffffffffffffu128
  let high_left = left >> 64
  let high_right = right >> 64
  let low = low_left * low_right
  let middle = core@1/int.wrapping_add(low_left * high_right, high_left * low_right)
  let bits = core@1/int.wrapping_add(low, middle << 64)
  core@1/int.truncate(bits)'''
    if signed:
        fields.update(
            SUB_OVERFLOW=(f'b > 0 && a < {minimum}{t} + b || '
                          f'b < 0 && a > {maximum}{t} + b'),
            MUL_CHECK=f'''  if a == 0 || b == 0 {{ return Some(0) }}
  if a > 0 {{
    if b > 0 {{
      if a > {maximum}{t} / b {{ return None }}
    }} else {{
      if b < {minimum}{t} / a {{ return None }}
    }}
  }} else {{
    if b > 0 {{
      if a < {minimum}{t} / b {{ return None }}
    }} else {{
      if a < {maximum}{t} / b {{ return None }}
    }}
  }}''',
            SUB_CLAMP=f'if b > 0 {{ {minimum}{t} }} else {{ {maximum}{t} }}',
            MUL_CLAMP=(f'if (a < 0) != (b < 0) {{ {minimum}{t} }} '
                       f'else {{ {maximum}{t} }}'),
            PARSE_VALUE=f'''      let raw = if negative {{ core@1/int.wrapping_add(~magnitude, 1) }} else {{ magnitude }}
      let wide: i128 = core@1/int.truncate(raw)
      let value: {t} = core@1/int.narrow(wide)''',
            FORMAT_MAGNITUDE='''  let wide: i128 = core@1/int.widen(value)
  let raw: u128 = core@1/int.truncate(wide)
  let magnitude = if value < 0 { core@1/int.wrapping_add(~raw, 1) } else { raw }''',
            NEGATIVE='value < 0',
        )
    else:
        fields.update(
            SUB_OVERFLOW='a < b',
            MUL_CHECK=f'  if b != 0 && a > {maximum}{t} / b {{ return None }}',
            SUB_CLAMP='0',
            MUL_CLAMP=f'{maximum}{t}',
            PARSE_VALUE=f'      let value: {t} = core@1/int.narrow(magnitude)',
            FORMAT_MAGNITUDE='  let magnitude: u128 = core@1/int.widen(value)',
            NEGATIVE='false',
        )
    text = TEMPLATE
    # Longer placeholders first: $MAXu128 and $T are intentional token joins.
    for key in sorted(fields, key=len, reverse=True):
        text = text.replace('$' + key, fields[key])
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for signed in (False, True):
        for width in (8, 16, 32, 64, 128):
            name = ('i' if signed else 'u') + str(width)
            path = ROOT / (name + '_ops.hir')
            text = module_text(signed, width)
            if args.check:
                if not path.exists() or path.read_text() != text:
                    parser.exit(1, f'{path}: regenerate with tools/generate-integer-ops.py\n')
            else:
                path.write_text(text)


if __name__ == '__main__':
    main()
