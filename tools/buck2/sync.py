def execution_sizes() -> str:
    """Measured requests stay separate from crate BUCK files."""
    data = json.loads(READS.text(HERE / "action-sizes.json"))
    profiles = data["profiles"]
    # The native-selection observation request (tools/buck2/native_selection.bzl).
    special = data.get("special_requests", {})
    budgets = {(1, 1048576, "")} | {(r["cpu_count"], r["memory_kb"], "fast" if name == "precheck" else "") for name, r in special.items()}
    requests = {}
    for profile in ("dev", "release"):
        requests[profile] = {}
        for target, row in sorted(profiles[profile].items()):
            cpu, memory = row["cpu_count"], row["memory_kb"]
            ceiling = 8 if target in CALIBRATED_CPUS[profile] else MAX_CPUS
            if type(cpu) is not int or not 1 <= cpu <= ceiling or type(memory) is not int or not 0 < memory <= 8388608:
                raise ValueError(f"invalid execution request: {profile}/{target}")
            if cpu != compile_cpus(profile, target, row.get("mean_cores", row["p95_cores"])):
                raise ValueError(f"stale CPU sizing: {profile}/{target}; regenerate action-sizes.json")
            budgets.add((cpu, memory, CPU_CLASSES[profile].get(target, "")))
            requests[profile][target] = [cpu, memory]
        for target, cpu_class in CPU_CLASSES[profile].items():
            cpu, memory = requests[profile].get(target, [1, 1048576])
            budgets.add((cpu, memory, cpu_class))
    # A profile with no fresh execution inherits the measured sibling's
    # request in platforms.bzl. Register its CPU class combination too.
    for profile in ("dev", "release"):
        other = "release" if profile == "dev" else "dev"
        for target in requests[other].keys() - requests[profile].keys():
            memory = requests[other][target][1]
            budgets.add((1, memory, CPU_CLASSES[profile].get(target, "")))
    return (HEADER + "# Requests derived from action-sizes.json; evidence and sizing policy in README.md.\n"
            + "POOL_BUDGETS = " + starlark([list(b) for b in sorted(budgets)]) + "\n\n"
            + "SPECIAL_REQUESTS = " + starlark({name: [r["cpu_count"], r["memory_kb"], "fast" if name == "precheck" else ""] for name, r in special.items()}) + "\n\n"
            + "COMPILE_REQUESTS = " + starlark(requests) + "\n\n"
            + "# The critical-path compiles that ask for the fast workers (action_sizes_from_log.py).\n"
            + "COMPILE_CLASSES = " + starlark({profile: dict(sorted(CPU_CLASSES[profile].items())) for profile in ("dev", "release")}) + "\n")


def check_classes(buck: str) -> None:
    """Every CPU_CLASSES row names a compile target: a renamed or split crate
    must not silently fall off the fast workers."""
    for profile, targets in CPU_CLASSES.items():
        for target in targets:
            if f'    name = "{target.removesuffix("-harness")}",\n' not in buck:
                raise SystemExit(f"CPU_CLASSES names no target: {profile}/{target} (tools/buck2/action_sizes_from_log.py)")


def check_test_data(buck: str) -> None:
    """Every TEST_DATA and FULL_GATE_SKIPS row names a test binary: a renamed one
    must not lose its data or start running its full-gate cases."""
    for binary in [*TEST_DATA, *FULL_GATE_SKIPS]:
        if f'    name = "{binary}",\n' not in buck:
            raise SystemExit(f"TEST_DATA or FULL_GATE_SKIPS names no test binary: {binary} (tools/buck2/sync.py)")


def generate(out_root: pathlib.Path, parts=tuple(generated.PARTS)) -> dict[str, generated.Reads]:
    """Write the named parts' outputs under `out_root`, each only where its
    bytes change; returns what each part read."""
    meta = metadata(ROOT / "Cargo.toml")
    found = {}
    if "third-party" in parts:
        found["third-party"] = write_third_party(meta, out_root / "third-party")
    if "first-party" in parts:
        found["first-party"] = write_first_party(meta, out_root)
    for reads in found.values():
        code_reads(reads)
    return found


def write_first_party(meta: dict, out_root: pathlib.Path) -> generated.Reads:
    global READS
    READS = generated.Reads(ROOT)
    corpus_packages.cache_clear()
    cargo_reads(READS, meta, layout=True)
    workspace = {p["id"] for p in meta["packages"] if p["id"] in meta["workspace_members"]}
    packages = [{"name": p["name"], "dependencies": [
        {key: (str(pathlib.Path(value).relative_to(ROOT)) if key == "path" and value else value)
         for key, value in dependency.items() if key in ("name", "kind", "path", "req", "uses_default_features")}
        for dependency in p["dependencies"]]} for p in meta["packages"] if p["id"] in workspace]
    contents = {
        "tools/buck2/workspace-metadata.json": json.dumps({"packages": packages}, indent=2, sort_keys=True) + "\n",
        "BUCK": root_buck(meta),
        "tools/buck2/exec_sizes.bzl": execution_sizes(),
        "tools/buck2/test_sizes.bzl": requests_bzl(json.loads(READS.text(HERE / "test-sizes.json"))),
        "tools/native-toolchain/pins.bzl": native_toolchain_pins(),
    }
    assert set(contents) == set(generated.PARTS["first-party"])
    for path, content in contents.items():
        write(out_root / path, content)
    return READS


def root_buck(meta: dict) -> str:
    buck = first_party(meta)
    check_classes(buck)
    check_test_data(buck)
    return buck


def native_toolchain_pins() -> str:
    directory = ROOT / "tools/native-toolchain"
    records = [line.split() for line in READS.text(directory / "llvm-23.lock").splitlines()
               if line and not line.startswith("#")]
    scalars = {row[0]: " ".join(row[1:]) for row in records if row[0] != "deb"}
    llvm = [{"url": f"{scalars['apt_pool']}/{name}_{scalars['apt_version'].split(':', 1)[1]}_{arch}.deb",
             "sha256": sha, "size": int(size)}
            for key, name, arch, sha, size in (row for row in records if row[0] == "deb")]
    runtime = json.loads(READS.text(HERE / "llvm-runtime-lock.json"))["debs"]
    llvm += [{"url": row["urls"][0].replace("http:", "https:"), "sha256": row["sha256"], "size": row["size"]}
             for row in runtime]
    pins = json.loads(READS.text(directory / "native.lock.json"))
    valgrind_runtime = pins.pop("valgrind_runtime")
    link_kit = pins.pop("link_kit")
    return (HEADER + "LLVM_DEBS = " + json.dumps(llvm, indent=4)
            + "\nLLD_SOURCE = " + json.dumps({"url": scalars["source_url"], "sha256": scalars["source_sha256"], "version": scalars["llvm_version"]}, indent=4)
            + "\nVALGRIND_DEBS = " + json.dumps(valgrind_runtime, indent=4)
            + "\nLINK_KIT = " + json.dumps(link_kit, indent=4)
            + "\nNATIVE = " + json.dumps({k: v for k, v in pins.items() if k != "schema"}, indent=4) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--if-stale", action="store_true",
                        help="regenerate only the parts whose outputs or inputs changed since they were generated")
    parser.add_argument("--check", action="store_true",
                        help="regenerate when stale, then check the sharded test binaries' test-cost coverage on the pool")
    parser.add_argument("--files-only", action="store_true", help="with --check, skip the pool's test-cost inventory")
    args = parser.parse_args()
    if not REINDEER.is_file():
        raise SystemExit("run tools/buck2/bootstrap.py first (Reindeer is missing)")
    parts = generated.stale(ROOT) if args.if_stale or args.check else list(generated.PARTS)
    if parts:
        for part, reads in generate(ROOT, parts).items():
            generated.record(ROOT, part, reads)
    if args.check and not args.files_only and (errors := check_cost_coverage()):
        print("\n".join(errors), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
