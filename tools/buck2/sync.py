def run(command, **kwargs) -> str:
    return subprocess.run(command, check=True, capture_output=True, text=True, **kwargs).stdout


def cargo() -> str:
    return os.environ.get("CARGO", "cargo")


def metadata(manifest: pathlib.Path, locked: bool = True) -> dict:
    command = [cargo(), "metadata", "--format-version", "1", "--filter-platform", HOST, "--manifest-path", str(manifest)]
    if locked:
        command.append("--locked")
    return json.loads(run(command, cwd=ROOT))


def starlark(value, indent: int = 4) -> str:
    """Render a JSON-like value in the layout buildifier uses for BUCK files."""
    pad = " " * indent
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, Raw):
        return value.text
    if isinstance(value, list):
        if not value:
            return "[]"
        if all(isinstance(v, (str, Raw)) for v in value) and len(value) == 1:
            return f"[{starlark(value[0])}]"
        inner = "".join(f"{pad}    {starlark(v, indent + 4)},\n" for v in value)
        return f"[\n{inner}{pad}]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        inner = "".join(f"{pad}    {json.dumps(k)}: {starlark(v, indent + 4)},\n" for k, v in value.items())
        return f"{{\n{inner}{pad}}}"
    if isinstance(value, int) and not isinstance(value, bool):
        return str(value)
    raise TypeError(value)


class Raw:
    def __init__(self, text: str):
        self.text = text


def call(rule: str, **attrs) -> str:
    body = "".join(f"    {key} = {starlark(value)},\n" for key, value in attrs.items() if value is not None)
    return f"{rule}(\n{body})\n"


# ---------------------------------------------------------------- third party

def third_party_manifest(meta: dict) -> str:
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    direct = {}
    for member in meta["workspace_members"]:
        for dep in nodes[member]["deps"]:
            package = packages[dep["pkg"]]
            if package["source"] is not None:
                direct[package["name"]] = (package["version"], sorted(nodes[dep["pkg"]]["features"]))
    lines = [
        HEADER.rstrip(),
        "# Every external crate a workspace member depends on, at the version and with",
        "# the features Cargo resolved for the whole workspace. Reindeer reads it.",
        "[package]",
        'name = "hirsel-third-party"',
        'version = "0.0.0"',
        'edition = "2024"',
        "publish = false",
        "",
        "[lib]",
        'path = "lib.rs"',
        "",
        "[workspace]",
        "",
        "[dependencies]",
    ]
    for name, (version, features) in sorted(direct.items()):
        listed = ", ".join(json.dumps(f) for f in features)
        lines.append(f'{name} = {{ version = "={version}", default-features = false, features = [{listed}] }}')
    return "\n".join(lines) + "\n"


def write_third_party(meta: dict, out: pathlib.Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    if out.resolve() != THIRD_PARTY.resolve():
        shutil.copytree(THIRD_PARTY / "fixups", out / "fixups")
        shutil.copyfile(THIRD_PARTY / "reindeer.toml", out / "reindeer.toml")
    (out / "Cargo.toml").write_text(third_party_manifest(meta), encoding="utf-8")
    (out / "lib.rs").write_text("// The package Reindeer reads; it has no code (tools/buck2/sync.py).\n", encoding="utf-8")
    # Start from the workspace's own lock so every version stays exactly as
    # Cargo resolved it; Cargo then drops the workspace members and adds this
    # package, choosing nothing new.
    shutil.copyfile(ROOT / "Cargo.lock", out / "Cargo.lock")
    metadata(out / "Cargo.toml", locked=False)
    workspace = {(p["name"], p["version"]) for p in tomllib.loads((ROOT / "Cargo.lock").read_text())["package"]}
    for package in tomllib.loads((out / "Cargo.lock").read_text())["package"]:
        if package["name"] != "hirsel-third-party" and (package["name"], package["version"]) not in workspace:
            raise SystemExit(f"third-party resolution chose {package['name']} {package['version']}, which Cargo.lock does not have")
    subprocess.run(
        [str(REINDEER), "--config", str(out / "reindeer.toml"), "buckify"],
        check=True, cwd=out, stdout=subprocess.DEVNULL,
    )


# ---------------------------------------------------------------- first party

def relative(path: pathlib.Path) -> str:
    return path.resolve().relative_to(ROOT).as_posix()


def references(source: pathlib.Path, seen: set[pathlib.Path]) -> set[str]:
    """Repository paths of the files `source` pulls in at compile time, transitively."""
    if source in seen or not source.is_file():
        return set()
    seen.add(source)
    found = set()
    text = source.read_text(encoding="utf-8", errors="replace")
    for prefix in set(INCLUDE_CONCAT.findall(text)):
        for match in LITERAL.finditer(text):
            target = (source.parent / (prefix + match.group(1))).resolve()
            if target.is_file() and target.is_relative_to(ROOT):
                found.add(relative(target))
    for match in INCLUDE.finditer(text):
        target = (source.parent / match.group(1)).resolve()
        found.add(relative(target))
        if target.suffix == ".rs":
            found |= references(target, seen)
    for match in PATH_ATTR.finditer(text):
        # `#[path]` is relative to the directory of the file holding it, or of a
        # non-mod.rs file's own module directory; both resolve in one of these.
        for base in (source.parent, source.with_suffix("")):
            target = (base / match.group(1)).resolve()
            if target.is_file():
                # Its own `mod x;` items live beside it, so take its directory.
                found.add("dir:" + relative(target.parent))
                found |= references(target, seen)
                for sibling in sorted(target.parent.rglob("*.rs")):
                    found |= references(sibling, seen)
                break
    return found


def sources(root_dir: pathlib.Path, crate_root: pathlib.Path) -> Raw:
    """A target's own directory, and the files it reaches outside it."""
    own = relative(root_dir)
    seen: set[pathlib.Path] = set()
    found: set[str] = set()
    for path in sorted(root_dir.rglob("*.rs")):
        found |= references(path, seen)
    found |= references(crate_root, seen)
    found.add(relative(crate_root))
    dirs = [own] + sorted({p.removeprefix("dir:") for p in found if p.startswith("dir:")})
    dirs = [d for d in dirs if not any(d.startswith(o + "/") for o in dirs if o != d)]
    extra = sorted(p for p in found if not p.startswith("dir:") and not any(p.startswith(d + "/") for d in dirs))
    expression = f"glob({starlark([d + '/**' for d in dirs], 4)})"
    if extra:
        expression += " + " + starlark(extra, 4)
    return Raw(expression)


DOC_BLOCK = re.compile(r'^\s*//[/!]\s*```', re.MULTILINE)


def has_doctests(package_dir):
    """Whether any documentation comment in the crate's src/ opens a code block."""
    return any(DOC_BLOCK.search(path.read_text()) for path in sorted((package_dir / "src").rglob("*.rs")))


def target_dir(package_dir: pathlib.Path, src: pathlib.Path) -> pathlib.Path:
    """The directory a Cargo target's sources live in."""
    rel = src.relative_to(package_dir)
    top = rel.parts[0]
    if top in ("src", "examples", "benches") and len(rel.parts) > 1:
        if top == "src":
            return package_dir / "src"
        return src.parent if src.name == "main.rs" else package_dir / top
    if top == "tests":
        # tests/it/main.rs owns tests/it; tests/x.rs owns tests/ but not
        # another binary's directory.
        return src.parent if src.name == "main.rs" else package_dir / "tests"
    return package_dir


def test_data(binary: str, package: str, package_dir: pathlib.Path, src: pathlib.Path) -> Raw:
    """What a test binary reads at run time: its crate's RUNTIME_DATA, its own
    TEST_DATA, and the non-Rust files of its own directory. A single-file
    `tests/<name>.rs` has no directory of its own: `tests/` holds its siblings.
    The package manifest keeps the directory the test runs from in its inputs."""
    paths = RUNTIME_DATA.get(package, []) + TEST_DATA.get(binary, []) + [relative(package_dir / "Cargo.toml")]
    expression = f"glob({starlark(paths, 4)})"
    if binary == "hirsel-lir-test-it":
        expression += ' + ["//tools/buck2:workspace-metadata.json"]'
    own = target_dir(package_dir, src)
    if own != package_dir / "tests":
        directory = relative(own)
        expression += f" + glob([{json.dumps(directory + '/**')}], exclude = [{json.dumps(directory + '/**/*.rs')}])"
    return Raw(expression)


def dependency_label(name: str, members: set[str]) -> str:
    return f"//:{name}" if name in members else f"//third-party:{name}"


def declared_deps(package: dict, packages: dict) -> list[str]:
    """A package's own required normal dependencies, as `cargo build -p` resolves them."""
    members = {p["name"] for p in packages.values() if p["source"] is None}
    return sorted(dependency_label(d["name"], members) for d in package["dependencies"]
                  if d["kind"] is None and not d["optional"])


def feature_deps(package: dict) -> dict[str, list[str]]:
    """The optional dependencies each feature enables (`dep:x`), transitively."""
    optional = {d["name"] for d in package["dependencies"] if d["optional"]}
    result = {}
    for feature in package["features"]:
        pending, seen, deps = [feature], set(), set()
        while pending:
            item = pending.pop()
            if item in seen:
                continue
            seen.add(item)
            for value in package["features"].get(item, []):
                dep = value.removeprefix("dep:").split("/")[0].removesuffix("?")
                if value.startswith("dep:") or dep in optional:
                    deps.add(f"//third-party:{dep}")
                else:
                    pending.append(value)
        if deps:
            result[feature] = sorted(deps)
    return result


def first_party(meta: dict) -> str:
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    opt_levels = dev_opt_levels()
    out = [
        HEADER,
        'load("//tools/buck2:defs.bzl", "hirsel_binary", "hirsel_build_script", "hirsel_command_test", "hirsel_library", "hirsel_runtime_archives", "hirsel_script_test", "hirsel_test")\n',
        'load("//tools/buck2:native_selection.bzl", "hirsel_native_selection")\n',
    ]

    def label(package_id: str) -> str:
        package = packages[package_id]
        return f"//:{package['name']}" if package_id in members else f"//third-party:{package['name']}"

    for member in sorted(members, key=lambda i: packages[i]["name"]):
        package = packages[member]
        name = package["name"]
        package_dir = pathlib.Path(package["manifest_path"]).parent
        manifest_dir = relative(package_dir)
        features = sorted(nodes[member]["features"])
        deps = {"normal": set(), "dev": set(), "build": set()}
        for dep in nodes[member]["deps"]:
            if dep["pkg"] == member:
                continue
            for kind in dep["dep_kinds"]:
                deps[kind["kind"] or "normal"].add(label(dep["pkg"]))
        common = {"manifest_dir": manifest_dir, "package_name": name, "version": package["version"], "edition": package["edition"]}
        profile = {"opt_level": opt_levels[name]} if name in opt_levels else {}
        runtime_archives = RUNTIME_ARCHIVES if name in NATIVE_TESTS else None

        def test_attrs(binary: str, src: pathlib.Path) -> dict:
            return dict(data=test_data(binary, name, package_dir, src), runtime_archives=runtime_archives,
                        seeded=seeded(target_dir(package_dir, src), src) or None, skips=FULL_GATE_SKIPS.get(binary))

        lib = next((t for t in package["targets"] if set(t["kind"]) & {"lib", "rlib", "staticlib"}), None)
        build = next((t for t in package["targets"] if t["kind"] == ["custom-build"]), None)
        build_script = None
        if build:
            build_script = f"{name}-build-script"
            src = pathlib.Path(build["src_path"])
            out.append("\n" + call(
                "hirsel_build_script",
                name=build_script,
                crate_root=relative(src),
                srcs=[relative(src)],
                deps=sorted(deps["build"]),
                inputs=Raw(f"glob({starlark(BUILD_SCRIPT_INPUTS[name], 4)})"),
                features=features,
                **common,
            ))
        normal = sorted(deps["normal"])
        test_deps = sorted(deps["normal"] | deps["dev"])
        if lib:
            src = pathlib.Path(lib["src_path"])
            attrs = dict(
                crate=lib["name"],
                crate_root=relative(src),
                srcs=sources(target_dir(package_dir, src), src),
                features=features,
                build_script=build_script and ":" + build_script,
                **common,
            )
            out.append("\n" + call("hirsel_library", **profile, name=name, deps=normal, doctests=has_doctests(package_dir) or None,
                                    **attrs))
            if "staticlib" in lib["crate_types"]:
                out.append("\n" + call(
                    "hirsel_runtime_archives",
                    name=f"{name}-archives",
                    deps=declared_deps(package, packages),
                    feature_deps=feature_deps(package),
                    **{**attrs, "features": ["default"], "build_script": None},
                ))
            if lib.get("test", True):
                out.append("\n" + call("hirsel_test", **profile, name=f"{name}-unittest", deps=test_deps,
                                        **test_attrs(f"{name}-unittest", src), **attrs))
        own = [f"//:{name}"] if lib else []
        for target in package["targets"]:
            kind = target["kind"][0]
            if kind not in ("bin", "test", "example"):
                continue
            src = pathlib.Path(target["src_path"])
            attrs = dict(
                crate=target["name"].replace("-", "_"),
                crate_root=relative(src),
                srcs=sources(target_dir(package_dir, src), src),
                features=features,
                **common,
            )
            if kind == "bin":
                out.append("\n" + call("hirsel_binary", **profile, name=f"{name}-bin-{target['name']}", bin_name=target["name"], deps=own + normal, **attrs))
                if target.get("test", True):
                    out.append("\n" + call("hirsel_test", **profile, name=f"{name}-bin-{target['name']}-unittest", deps=own + normal,
                                             **test_attrs(f"{name}-bin-{target['name']}-unittest", src), **attrs))
            elif kind == "example":
                out.append("\n" + call("hirsel_binary", **profile, name=f"{name}-example-{target['name']}", bin_name=target["name"], deps=own + test_deps, **attrs))
            else:
                binaries = {
                    t["name"]: f"//:{name}-bin-{t['name']}"
                    for t in package["targets"] if t["kind"] == ["bin"]
                }
                count, costs = shards(f"{name}-test-{target['name']}")
                out.append("\n" + call("hirsel_test", **profile, name=f"{name}-test-{target['name']}", deps=own + test_deps, bin_exes=binaries,
                                         shards=count if count > 1 else None, costs=costs,
                                         **test_attrs(f"{name}-test-{target['name']}", src), **attrs))
    out.append("\n" + call("hirsel_native_selection", name="native-selection", collector="//:hirsel-conformance-bin-native-select", data=Raw(f"glob({starlark(CORPUS, 4)})")))
    for gate in GATE_TESTS:
        out.append("\n" + call("hirsel_command_test", **gate, data=Raw(f"glob({starlark(CORPUS, 4)})")))
    for name, script, data, archives in (
        ("gate-native-runtime-c", "crates/hirsel-rt/harness/run.sh", ["crates/hirsel-rt/harness/**", "crates/hirsel-rt/include/**"], RUNTIME_ARCHIVES),
        ("gate-native-library-c", "native-tests/library/run-c.sh", ["native-tests/library/**", "crates/hirsel-rt/include/**", "stdlib/native/**"], RUNTIME_ARCHIVES),
        ("gate-native-toolchain-pin", "tools/native-toolchain/check", ["tools/native-toolchain/llvm-21.lock", "tools/native-toolchain/check", "tools/native-toolchain/fixtures/**", "Cargo.lock"], None),
    ):
        out.append("\n" + call("hirsel_script_test", name=name, script=script, data=Raw(f"glob({starlark(data, 4)})"), runtime_archives=archives))
    return "".join(out)


