#!/usr/bin/env python3
"""Generate markdown entity/punctuation data and published conformance vectors.

Usage: tools/generate-markdown.py /tmp/ref-commonmark-js /tmp/ref-cmark-gfm --cmark-build /tmp/ref-cmark-gfm-build
Build cmark-gfm with CMake and CMARK_SHARED=ON before regenerating.
The reference checkouts must match their pinned revisions below. Unicode
punctuation/symbol data comes from stdlib/unicode16/UnicodeData.txt.
"""
import argparse
import ctypes
import json
import re
import subprocess
from pathlib import Path

COMMONMARK = '898886961b49c1df1175666d03c3ac66c9cc9040'
CMARK_GFM = '27d942c8b0a62d192f616e5bf3578f4b6a89e180'
ROOT = Path(__file__).resolve().parents[1]
BIDI = {0x061C, 0x200E, 0x200F, *range(0x202A, 0x202F), *range(0x2066, 0x206A)}


def literal(s):
    result = '"'
    for c in s:
        result += {'"': '\\"', '\\': '\\\\', '\n': '\\n', '\r': '\\r', '\t': '\\t'}.get(c, '\\u{%x}' % ord(c) if ord(c) < 32 or ord(c) == 127 or ord(c) in BIDI else c)
    return result + '"'


def byte_literal(data):
    return 'b"' + ''.join('\\x%02x' % n for n in data) + '"'


def tables(cmark):
    raw = (cmark / 'src/entities.inc').read_text()
    entities = []
    for name, data in re.findall(r'\{\(unsigned char\*\)"(\w+)", \{([\d, ]+)\}\}', raw):
        entities.append((name, bytes(int(x) for x in data.split(',') if x.strip())[:-1].decode()))
    assert len(entities) == 2125
    data = ''
    offsets = bytearray()
    for name, value in entities:
        offsets += len(data.encode()).to_bytes(3, 'little')
        data += name + '\0' + value + '\0'
    punct = []
    for line in (ROOT / 'stdlib/unicode16/UnicodeData.txt').read_text().splitlines():
        fields = line.split(';')
        if fields[2][0] in 'PS':
            n = int(fields[0], 16)
            if punct and punct[-1][1] + 1 == n:
                punct[-1][1] = n
            else:
                punct.append([n, n])
    packed = b''.join(a.to_bytes(3, 'little') + b.to_bytes(3, 'little') for a, b in punct)
    out = '// Generated by tools/generate-markdown.py; do not edit.\n'
    out += '// cmark-gfm entities.inc and Unicode16 UnicodeData P/S categories.\n'
    out += 'const ENTITY_DATA: String = ' + literal(data) + '\n\n'
    out += 'const ENTITY_INDEX: Bytes = ' + byte_literal(offsets) + '\n\n'
    out += 'const PUNCTUATION: Bytes = ' + byte_literal(packed) + '\n'
    (ROOT / 'stdlib/std@1/markdown_tables.hir').write_text(out)


def examples(path):
    section = ''
    state = 0
    number = 0
    source = []
    expected = []
    for line in path.read_text().splitlines(keepends=True):
        if state == 0:
            if re.match(r'^`{32} example', line):
                source = []
                expected = []
                state = 1
            elif line.startswith('## '):
                section = line[3:].strip()
        elif line.rstrip() == '`' * 32:
            number += 1
            yield section, number, ''.join(source).replace('→', '\t'), ''.join(expected).replace('→', '\t')
            state = 0
        elif line.rstrip() == '.' and state == 1:
            state = 2
        elif state == 1:
            source.append(line)
        else:
            expected.append(line)


def gfm_renderer(build):
    """Render with the pinned cmark-gfm C API, retaining no parser allocations."""
    pointer = ctypes.c_void_p
    lib = ctypes.CDLL(str(build / 'src/libcmark-gfm.so'), mode=ctypes.RTLD_GLOBAL)
    ext = ctypes.CDLL(str(build / 'extensions/libcmark-gfm-extensions.so'))
    ext.cmark_gfm_core_extensions_ensure_registered()
    signatures = [
        ('cmark_parser_new', [ctypes.c_int], pointer),
        ('cmark_find_syntax_extension', [ctypes.c_char_p], pointer),
        ('cmark_parser_attach_syntax_extension', [pointer, pointer], ctypes.c_int),
        ('cmark_parser_feed', [pointer, ctypes.c_char_p, ctypes.c_size_t], None),
        ('cmark_parser_finish', [pointer], pointer),
        ('cmark_parser_get_syntax_extensions', [pointer], pointer),
        ('cmark_render_html', [pointer, ctypes.c_int, pointer], pointer),
        ('cmark_node_free', [pointer], None),
        ('cmark_parser_free', [pointer], None),
    ]
    for name, args, result in signatures:
        function = getattr(lib, name)
        function.argtypes = args
        function.restype = result
    libc = ctypes.CDLL(None)
    libc.free.argtypes = [pointer]
    libc.free.restype = None

    def render(source):
        parser = lib.cmark_parser_new(0)
        for name in (b'table', b'strikethrough', b'autolink', b'tasklist'):
            assert lib.cmark_parser_attach_syntax_extension(parser, lib.cmark_find_syntax_extension(name))
        data = source.encode()
        lib.cmark_parser_feed(parser, data, len(data))
        root = lib.cmark_parser_finish(parser)
        extensions = lib.cmark_parser_get_syntax_extensions(parser)
        output = lib.cmark_render_html(root, 1 << 17, extensions)  # CMARK_OPT_UNSAFE: retain raw HTML.
        result = ctypes.string_at(output).decode()
        libc.free(output)
        lib.cmark_node_free(root)
        lib.cmark_parser_free(parser)
        # cmark-gfm emits equivalent XHTML checkbox tags; use the GFM spec's
        # published HTML serialization. The golden comparison below checks it.
        return result.replace('<input type="checkbox" checked="" disabled="" />',
                              '<input checked="" disabled="" type="checkbox">').replace(
                                  '<input type="checkbox" disabled="" />',
                                  '<input disabled="" type="checkbox">')

    return render


def vectors(commonmark, cmark, cmark_build):
    out = ROOT / 'conformance/SEM'
    selected = {'Tables (extension)', 'Task list items (extension)', 'Strikethrough (extension)', 'Autolinks (extension)'}
    groups = {}
    for flavor, checkout in (('commonmark', commonmark), ('gfm', cmark)):
        for section, number, source, expected in examples(checkout / 'test/spec.txt'):
            if flavor == 'gfm' and section not in selected:
                continue
            groups.setdefault((flavor, section), []).append((number, source, expected))
    # Malformed twins are independently rendered by the pinned CommonMark parser.
    # Each is truncated mid-input and gains an unterminated label/entity plus NUL.
    # GFM twins use cmark-gfm with the same four extensions enabled.
    all_sources = [source[:len(source) // 2] + '\0[&unterminated' for (flavor, _), cases in groups.items() if flavor == 'commonmark' for _, source, _ in cases]
    js = "import fs from 'node:fs'; import {Parser,HtmlRenderer} from './lib/index.js'; const p=new Parser(),r=new HtmlRenderer(); process.stdout.write(JSON.stringify(JSON.parse(fs.readFileSync(0,'utf8')).map(s=>r.render(p.parse(s)))));"
    twins = iter(json.loads(subprocess.check_output(['node', '--input-type=module', '-e', js], cwd=commonmark, input=json.dumps(all_sources), text=True)))
    render_gfm = gfm_renderer(cmark_build)
    paths = []
    counts = {}
    # One program holds as many vectors as fit 19 of the old 1M-step shards (a
    # shard of 350k estimated cost, both twins counted, always ran under 1M
    # steps): a program costs about 6 s of gate time before its first vector,
    # so it raises its own step budget instead of fitting the default.
    suites = {}
    for (flavor, section), cases in groups.items():
        counts[f'{flavor}: {section}'] = len(cases)
        for number, source, expected in cases:
            twin_source = source[:len(source) // 2] + '\0[&unterminated'
            if flavor == 'gfm':
                assert render_gfm(source) == expected, f'GFM reference drift: {section}/{number}'
                twin_expected = render_gfm(twin_source)
            else:
                twin_expected = next(twins)
            suites.setdefault(flavor, []).append((section, number, source, expected, twin_source, twin_expected))
    for flavor, cases in suites.items():
        for twin in (False, True):
            batches = [[]]
            spent = [0]
            for case in cases:
                cost = 20000 + 900 * (len(case[2].encode()) + len(case[4].encode()))
                if batches[-1] and spent[-1] + cost > 19 * 350000:
                    batches.append([])
                    spent.append(0)
                batches[-1].append(case)
                spent[-1] += cost
            for index, batch in enumerate(batches, 1):
                stem = f'SEM-3-markdown-{flavor}-{index}' + ('-malformed-run' if twin else '-run')
                steps = -(-spent[index - 1] // 350000) * 1000000
                lines = ['// rule: SEM-3', '// expect: run', f'// steps: {steps}', '// one program runs this batch of the suite, which outgrows the default budget', '// Published spec.txt vectors; tools/generate-markdown.py.', 'fn grant_error(take e: GrantError) -> () {}', '', 'pub fn main(rt: Io) -> Result[(), ()] {', '  let s = io.stdout(rt) ? grant_error', '  let mut failed: u64 = 0']
                for section, number, source, expected, twin_source, twin_expected in batch:
                    options = 'std@1/markdown.gfm_options()' if flavor == 'gfm' else 'std@1/markdown.default_options()'
                    label = f'{flavor}/{section}/{number}' + ('/malformed' if twin else '')
                    lines.append(f'  failed += harness.check(s, {literal(label)}, {literal(twin_source if twin else source)}, {literal(twin_expected if twin else expected)}, {options})')
                lines += ['  failure.check(failed == 0, TextInvariant())', '  Ok(())', '}', '']
                path = out / (stem + '.hir')
                path.write_text('\n'.join(lines))
                paths.append(path)
                manifest = {'schema': 1, 'package': {'name': 'application', 'version': '1'}, 'entry': {'module': [], 'name': 'main'}, 'sources': [{'path': stem + '.hir', 'module': []}, {'path': '../../packages/fixtures/markdown_vectors@1/harness.hir', 'module': ['harness']}], 'dependencies': [{'manifest': '../../stdlib/std@1/hirsel.json', 'package': {'name': 'std', 'version': '1'}, 'expose': []}]}
                (out / (stem + '.hir.json')).write_text(json.dumps(manifest, indent=2) + '\n')
    for section, count in counts.items():
        print(f'{section}: {count} published + {count} malformed')
    print(f'{sum(counts.values())} published vectors, {len(paths)} programs')
    return paths


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('commonmark', type=Path)
    parser.add_argument('cmark_gfm', type=Path)
    parser.add_argument('--cmark-build', type=Path, required=True, help='pinned cmark-gfm CMake shared-library build')
    parser.add_argument('--hirsel', type=Path, help='format generated conformance programs')
    args = parser.parse_args()
    for path, expected in ((args.commonmark, COMMONMARK), (args.cmark_gfm, CMARK_GFM)):
        actual = subprocess.check_output(['git', '-C', str(path), 'rev-parse', 'HEAD'], text=True).strip()
        if actual != expected:
            parser.error(f'{path}: expected {expected}, found {actual}')
    tables(args.cmark_gfm)
    paths = vectors(args.commonmark, args.cmark_gfm, args.cmark_build)
    if args.hirsel:
        for path in paths:
            subprocess.run([str(args.hirsel.resolve()), 'fmt', str(path)], check=True)


if __name__ == '__main__':
    main()
