#!/usr/bin/env python3
"""Generate the binary32/64 rounding, square-root, sign and scaling functions.

Run with --check to verify the checked-in sources against this template.
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'stdlib/std@1'

TEMPLATE = '''// Generated by tools/generate-float-math.py; edit the template there.
// trunc, floor, ceil, round, sqrt, abs and fma are core primitives, as Rust's
// intrinsics and Zig's builtins are (docs/spec/core-library.md); fract is
// Rust's library form over trunc. copysign and scaled follow the Rust libm
// crate's generic copysign and scalbn (Zig's math/copysign.zig is library
// code too), powi compiler-builtins' float/pow.rs (MIT; third-party/NOTICES.md).
@noalloc
pub fn trunc(value: $T) -> $T uses {} { core@1/float.trunc(value) }

@noalloc
pub fn floor(value: $T) -> $T uses {} { core@1/float.floor(value) }

@noalloc
pub fn ceil(value: $T) -> $T uses {} { core@1/float.ceil(value) }

@noalloc
pub fn round(value: $T) -> $T uses {} { core@1/float.round(value) }

@noalloc
pub fn sqrt(value: $T) -> $T uses {} { core@1/float.sqrt(value) }

@noalloc
pub fn fract(value: $T) -> $T uses {} { value - core@1/float.trunc(value) }

@noalloc
pub fn abs(value: $T) -> $T uses {} { core@1/float.abs(value) }

@noalloc
pub fn copysign(magnitude: $T, sign: $T) -> $T uses {} {
  let bits = core@1/$T.bits(magnitude) & $MAGNITUDE$U
  core@1/$T.from_bits(bits | (core@1/$T.bits(sign) & $SIGN$U))
}

@noalloc
pub fn fma(a: $T, b: $T, c: $T) -> $T uses {} { core@1/float.mul_add(a, b, c) }

@noalloc
pub fn powi(base: $T, exponent: i32) -> $T uses {} {
  let wide: i64 = core@1/int.widen(exponent)
  let mut count: u32 = core@1/int.narrow(if wide < 0 { -wide } else { wide })
  let mut a = base
  let mut product: $T = 1$T
  while true {
    if count & 1 != 0 { product *= a }
    count >>= 1
    if count == 0 { break }
    a *= a
  }
  if exponent < 0 { 1$T / product } else { product }
}

// x * 2^n without intermediate overflow or double rounding.
@noalloc
fn scaled(value: $T, exponent: i32) -> $T uses {} {
  let mut x = value
  let mut n = exponent
  if n > $EMAX {
    x *= core@1/$T.from_bits($MAXPOW$U)
    n -= $EMAX
    if n > $EMAX {
      x *= core@1/$T.from_bits($MAXPOW$U)
      n -= $EMAX
      if n > $EMAX { n = $EMAX }
    }
  } else if n < -$EMIN {
    x *= core@1/$T.from_bits($MINPOW$U)
    n += $MINADD
    if n < -$EMIN {
      x *= core@1/$T.from_bits($MINPOW$U)
      n += $MINADD
      if n < -$EMIN { n = -$EMIN }
    }
  }
  let biased: $U = core@1/int.narrow(n + $BIAS)
  x * core@1/$T.from_bits(biased << $SHIFT)
}

// Rust's saturating `as i32`: NaN is zero and out-of-range values clamp.
@noalloc
fn saturated_i32(value: $T) -> i32 uses {} {
  match core@1/float.to_i32(value) {
    Ok(n) => n,
    Error(_) => if value != value {
      0
    } else if value > 0$T {
      2147483647
    } else {
      -2147483648
    },
  }
}

@noalloc
fn of_i32(n: i32) -> $T uses {} { core@1/float.from_int(n) }
'''


def module_text(width, shift, bias, exponent):
    fields = {
        'T': 'f' + str(width),
        'U': 'u' + str(width),
        'SHIFT': shift,
        'MASK': (1 << exponent) - 1,
        'BIAS': bias,
        'INTEGER': bias + shift,
        'SIGN': 1 << (width - 1),
        'INFINITY': ((1 << exponent) - 1) << shift,
        'NAN': (((1 << exponent) - 1) << shift) | (1 << (shift - 1)),
        'FRACTION': (1 << shift) - 1,
        'EXTRA': shift + 1,
        'MAGNITUDE': (1 << (width - 1)) - 1,
        'EMAX': bias,
        'EMIN': bias - 1,
        'MAXPOW': (2 * bias) << shift,
        'MINPOW': (shift + 2) << shift,
        'MINADD': bias - 1 - (shift + 1),
    }
    text = TEMPLATE
    for key in sorted(fields, key=len, reverse=True):
        text = text.replace('$' + key, str(fields[key]))
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for width, shift, bias, exponent in [(32, 23, 127, 8), (64, 52, 1023, 11)]:
        path = ROOT / f'f{width}_math.hir'
        text = module_text(width, shift, bias, exponent)
        if args.check:
            if not path.exists() or path.read_text() != text:
                parser.exit(1, f'{path}: regenerate with tools/generate-float-math.py\n')
        else:
            path.write_text(text)


if __name__ == '__main__':
    main()
