#!/usr/bin/env python3
"""Generate the portable binary32/64 rounding, square-root, sign and scaling kernels.

Run with --check to verify the checked-in sources against this template.
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'stdlib/std@1'

TEMPLATE = '''// Generated by tools/generate-float-math.py; edit the template there.
// Go math/floor.go and math/sqrt.go portable kernels.
// Copyright 2009 The Go Authors. BSD-3-Clause; third-party/NOTICES.md.
// sqrt preserves the Sun Microsystems permission notice recorded there.
// copysign and scaled follow the Rust libm crate's generic copysign and
// scalbn, powi compiler-builtins' float/pow.rs (MIT; third-party/NOTICES.md).
@noalloc
pub fn trunc(value: $T) -> $T uses {} {
  let bits: u64 = core@1/int.widen(core@1/$T.bits(value))
  let exponent = (bits >> $SHIFT) & $MASKu64
  if exponent < $BIAS { return core@1/$T.from_bits(core@1/int.narrow(bits & $SIGNu64)) }
  if exponent >= $INTEGER { return value }
  let fraction = (1u64 << ($INTEGERu64 - exponent)) - 1
  core@1/$T.from_bits(core@1/int.narrow(bits & ~fraction))
}

@noalloc
pub fn floor(value: $T) -> $T uses {} {
  let integer = trunc(value)
  if value < integer { integer - 1$T } else { integer }
}

@noalloc
pub fn ceil(value: $T) -> $T uses {} { -floor(-value) }

@noalloc
pub fn round(value: $T) -> $T uses {} {
  let integer = trunc(value)
  let fraction = value - integer
  if fraction >= 0.5$T { return integer + 1$T }
  if fraction <= -0.5$T { return integer - 1$T }
  integer
}

@noalloc
pub fn sqrt(value: $T) -> $T uses {} {
  let mut bits: u64 = core@1/int.widen(core@1/$T.bits(value))
  if value == 0$T || value != value || bits == $INFINITYu64 { return value }
  if value < 0$T { return core@1/$T.from_bits($NAN$U) }
  let biased: i32 = core@1/int.narrow((bits >> $SHIFT) & $MASKu64)
  let mut exponent = biased
  if exponent == 0 {
    while bits & (1u64 << $SHIFT) == 0 {
      bits <<= 1
      exponent -= 1
    }
    exponent += 1
  }
  exponent -= $BIAS
  bits = (bits & $FRACTIONu64) | (1u64 << $SHIFT)
  if exponent & 1 != 0 { bits <<= 1 }
  exponent >>= 1
  bits <<= 1
  let mut q: u64 = 0
  let mut s: u64 = 0
  let mut r: u64 = 1u64 << $EXTRA
  while r != 0 {
    let trial = s + r
    if trial <= bits {
      s = trial + r
      bits -= trial
      q += r
    }
    bits <<= 1
    r >>= 1
  }
  if bits != 0 { q += q & 1 }
  let result_exponent: u64 = core@1/int.narrow(exponent - 1 + $BIAS)
  let result_bits = (q >> 1) + (result_exponent << $SHIFT)
  core@1/$T.from_bits(core@1/int.narrow(result_bits))
}

@noalloc
pub fn fract(value: $T) -> $T uses {} { value - trunc(value) }

@noalloc
pub fn abs(value: $T) -> $T uses {} {
  core@1/$T.from_bits(core@1/$T.bits(value) & $MAGNITUDE$U)
}

@noalloc
pub fn copysign(magnitude: $T, sign: $T) -> $T uses {} {
  let bits = core@1/$T.bits(magnitude) & $MAGNITUDE$U
  core@1/$T.from_bits(bits | (core@1/$T.bits(sign) & $SIGN$U))
}

@noalloc
pub fn fma(a: $T, b: $T, c: $T) -> $T uses {} { core@1/float.mul_add(a, b, c) }

@noalloc
pub fn powi(base: $T, exponent: i32) -> $T uses {} {
  let wide: i64 = core@1/int.widen(exponent)
  let mut count: u32 = core@1/int.narrow(if wide < 0 { -wide } else { wide })
  let mut a = base
  let mut product: $T = 1$T
  while true {
    if count & 1 != 0 { product *= a }
    count >>= 1
    if count == 0 { break }
    a *= a
  }
  if exponent < 0 { 1$T / product } else { product }
}

// x * 2^n without intermediate overflow or double rounding.
@noalloc
fn scaled(value: $T, exponent: i32) -> $T uses {} {
  let mut x = value
  let mut n = exponent
  if n > $EMAX {
    x *= core@1/$T.from_bits($MAXPOW$U)
    n -= $EMAX
    if n > $EMAX {
      x *= core@1/$T.from_bits($MAXPOW$U)
      n -= $EMAX
      if n > $EMAX { n = $EMAX }
    }
  } else if n < -$EMIN {
    x *= core@1/$T.from_bits($MINPOW$U)
    n += $MINADD
    if n < -$EMIN {
      x *= core@1/$T.from_bits($MINPOW$U)
      n += $MINADD
      if n < -$EMIN { n = -$EMIN }
    }
  }
  let biased: $U = core@1/int.narrow(n + $BIAS)
  x * core@1/$T.from_bits(biased << $SHIFT)
}

// Rust's saturating `as i32`: NaN is zero and out-of-range values clamp.
@noalloc
fn saturated_i32(value: $T) -> i32 uses {} {
  match core@1/float.to_i32(value) {
    Ok(n) => n,
    Error(_) => if value != value {
      0
    } else if value > 0$T {
      2147483647
    } else {
      -2147483648
    },
  }
}

@noalloc
fn of_i32(n: i32) -> $T uses {} { core@1/float.from_int(n) }
'''


def module_text(width, shift, bias, exponent):
    fields = {
        'T': 'f' + str(width),
        'U': 'u' + str(width),
        'SHIFT': shift,
        'MASK': (1 << exponent) - 1,
        'BIAS': bias,
        'INTEGER': bias + shift,
        'SIGN': 1 << (width - 1),
        'INFINITY': ((1 << exponent) - 1) << shift,
        'NAN': (((1 << exponent) - 1) << shift) | (1 << (shift - 1)),
        'FRACTION': (1 << shift) - 1,
        'EXTRA': shift + 1,
        'MAGNITUDE': (1 << (width - 1)) - 1,
        'EMAX': bias,
        'EMIN': bias - 1,
        'MAXPOW': (2 * bias) << shift,
        'MINPOW': (shift + 2) << shift,
        'MINADD': bias - 1 - (shift + 1),
    }
    text = TEMPLATE
    for key in sorted(fields, key=len, reverse=True):
        text = text.replace('$' + key, str(fields[key]))
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for width, shift, bias, exponent in [(32, 23, 127, 8), (64, 52, 1023, 11)]:
        path = ROOT / f'f{width}_math.hir'
        text = module_text(width, shift, bias, exponent)
        if args.check:
            if not path.exists() or path.read_text() != text:
                parser.exit(1, f'{path}: regenerate with tools/generate-float-math.py\n')
        else:
            path.write_text(text)


if __name__ == '__main__':
    main()
