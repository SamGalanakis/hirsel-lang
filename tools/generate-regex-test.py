#!/usr/bin/env python3
"""Import Go's regexp vectors, retaining source lines and every exclusion.

Usage: tools/generate-regex-test.py <golang/go checkout> [--hirsel <binary>]
The checkout must be at COMMIT. Expectations come from the reference tables,
never from Hirsel. Every included search calls compile before find, so a
classifier mistake is a failing test rather than a silently dropped pattern.

The RE2 reader follows Go exec_test.go:70-200 (ordered partial-match column).
findTests uses the first whole span, as find_test.go:253-258 does; max=0 has
no Find expectation. Invalid strings are decoded as bytes before UTF-8 checks.
"""

import argparse
from collections import Counter
import json
from pathlib import Path
import re
import subprocess

COMMIT = 'ebe2feefc400f813aefdc8a036e66d2619da6649'
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'conformance/SEM'
FIXTURES = ROOT / 'crates/hirsel-driver/tests/fixtures'
# Individually measured above 1M interpreter steps. Keep their exact strings
# as driver fixtures with an explicit Rust test budget, never a corpus override.
LARGE_INVALID = {505, 506, 507}
STRING = r'`[^`]*`|"(?:[^"\\]|\\.)*"'
HEADER = '''// rule: SEM-3
// expect: run
// Generated by tools/generate-regex-test.py; Go ebe2feef (BSD-3-Clause).
// RE2 search data: Copyright (c) 2009 The RE2 Authors (BSD-3-Clause).
'''
SEARCH = '''fn check(pattern: String, input: String, expected: Option[regex.Span]) -> Result[(), ()] {
  let re = match regex.compile(pattern, 10000) {
    Ok(re) => take re,
    Error(_) => return Error(()),
  }
  failure.check(regex.find(re, input, 100000) == Ok(expected), TextInvariant())
  Ok(())
}
'''
INVALID = '''fn invalid(pattern: String, size_error: bool) {
  failure.check(
    match regex.compile(pattern, 1000) {
      Error(Syntax(_)) => !size_error,
      Error(ProgramTooLarge()) => size_error,
      _ => false,
    },
    TextInvariant()
  )
}
'''


def unquote(literal):
    """Go strconv.Unquote's byte semantics for the strings in these tables."""
    if literal.startswith('`'):
        return literal[1:-1].replace('\r', '').encode()
    out = bytearray()
    text = literal[1:-1]
    at = 0
    escapes = dict(zip('abfnrtv\\"\'', [7, 8, 12, 10, 13, 9, 11, 92, 34, 39]))
    while at < len(text):
        c = text[at]
        at += 1
        if c != '\\':
            out.extend(c.encode())
            continue
        c = text[at]
        at += 1
        if c in escapes:
            out.append(escapes[c])
        elif c in 'xuU':
            count = {'x': 2, 'u': 4, 'U': 8}[c]
            cp = int(text[at:at + count], 16)
            at += count
            out.extend(bytes([cp]) if c == 'x' else chr(cp).encode())
        elif c in '01234567':
            out.append(int(c + text[at:at + 2], 8))
            at += 2
        else:
            raise ValueError(f'unknown Go string escape {c!r}')
    return bytes(out)


def literal(text):
    out = ['"']
    for c in text:
        cp = ord(c)
        if c in '\\"':
            out.append('\\' + c)
        elif c in '\n\r\t':
            out.append({'\n': '\\n', '\r': '\\r', '\t': '\\t'}[c])
        elif cp < 32 or 127 <= cp < 160 or cp in {0x2028, 0x2029}:
            out.append('\\u{%x}' % cp)
        else:
            out.append(c)
    return ''.join(out) + '"'


def outside(pattern):
    """Lexical dialect filter, independent of whether Hirsel compiles it."""
    at = 0
    in_class = False
    first = False
    while at < len(pattern):
        c = pattern[at]
        at += 1
        if c == '\\':
            if at == len(pattern):
                break  # malformed, but in dialect (invalidRegexps)
            escape = pattern[at]
            at += 1
            if escape.isascii() and escape.isalnum() and escape not in 'dDsSwWnrtfavAbBz':
                return f'unsupported escape \\{escape}'
            if in_class:
                first = False
        elif in_class:
            if c == '[' and pattern[at:at + 1] == ':':
                return 'POSIX class'
            if c == ']' and not first:
                in_class = False
            first = False
        elif c == '[':
            in_class = True
            first = True
            if pattern[at:at + 1] == '^':
                at += 1
        elif c == '(' and pattern[at:at + 1] == '?' and pattern[at:at + 2] != '?:':
            return 'flags, named groups or lookaround'
    return None


def search_call(pattern, text, span):
    expected = 'None()' if span is None else f'Some(regex.Span(start: {span[0]}, end: {span[1]}))'
    return f'  check({literal(pattern)}, {literal(text)}, {expected})?'


def re2_rows(source):
    strings = []
    in_strings = False
    at = 0
    for line, row in enumerate(source.splitlines(), 1):
        if not row or row.startswith('#') or row[0].isupper():
            continue
        if row == 'strings':
            strings = []
            in_strings = True
        elif row == 'regexps':
            in_strings = False
        elif row.startswith('"'):
            value = unquote(row)
            if in_strings:
                strings.append(value)
            else:
                pattern = value
                at = 0
        else:
            cells = row.split(';')
            assert len(cells) == 4 and at < len(strings), (line, row)
            whole = cells[1].split()[0]
            span = None if whole == '-' else tuple(map(int, whole.split('-')))
            yield line, pattern, strings[at], span
            at += 1


def find_rows(source):
    start = source.index('var findTests = []FindTest{')
    end = source.index('\n}', start)
    row = re.compile(r'\{\s*(' + STRING + r')\s*,\s*(' + STRING +
                     r')\s*,\s*(-?\d+)\s*,\s*(nil|build\([^)]*\))\s*,?\s*\}', re.S)
    for match in row.finditer(source, start, end):
        pattern, text, maximum, spans = match.groups()
        numbers = list(map(int, re.findall(r'-?\d+', spans)))
        span = tuple(numbers[1:3]) if numbers else None
        yield source.count('\n', 0, match.start()) + 1, unquote(pattern), unquote(text), int(maximum), span


def expressions(source):
    """The invalidRegexps table: quoted strings, + and strings.Repeat only."""
    start = source.index('var invalidRegexps = []string{')
    start = source.index('\n', start) + 1
    end = source.index('\n}', start)
    token = re.compile(r'(' + STRING + r')|//[^\n]*|strings\.Repeat|-?\d+|[()+,]|\s+', re.S)
    tokens = []
    for match in token.finditer(source, start, end):
        value = match.group()
        if not value.isspace() and not value.startswith('//'):
            tokens.append((value, source.count('\n', 0, match.start()) + 1))
    at = 0

    def expr():
        nonlocal at
        value = tokens[at][0]
        at += 1
        if value == 'strings.Repeat':
            assert tokens[at][0] == '('
            at += 1
            result = expr()
            assert tokens[at][0] == ','
            result *= int(tokens[at + 1][0])
            assert tokens[at + 2][0] == ')'
            at += 3
        else:
            result = unquote(value)
        if at < len(tokens) and tokens[at][0] == '+':
            at += 1
            result += expr()
        return result

    while at < len(tokens):
        line = tokens[at][1]
        value = expr()
        assert tokens[at][0] == ','
        at += 1
        yield line, value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('go', type=Path)
    parser.add_argument('--hirsel', type=Path)
    args = parser.parse_args()
    actual = subprocess.check_output(['git', '-C', str(args.go), 'rev-parse', 'HEAD'], text=True).strip()
    if actual != COMMIT:
        parser.error(f'expected Go {COMMIT}, got {actual}')
    skipped = []
    counts = Counter()
    programs = []
    large_programs = []
    # Only remove this generator's previous outputs (chunk sizes can change).
    for name in ('re2', 'find', 'invalid'):
        for path in OUT.glob(f'SEM-3-regex-{name}-[0-9][0-9][0-9]-run.hir*'):
            path.unlink()

    def skip(table, line, reason):
        skipped.append((table, line, reason))

    def decode(table, line, pattern, text=b''):
        try:
            pattern, text = pattern.decode(), text.decode()
        except UnicodeDecodeError:
            skip(table, line, 'invalid UTF-8 cannot inhabit Hirsel String')
            return None
        reason = outside(pattern)
        if reason:
            skip(table, line, reason)
            return None
        return pattern, text

    def write(table, calls, harness):
        # Small independent programs: expensive combinations get their own
        # program, keeping every fixture below the 1M interpreter-step budget.
        chunks = []
        chunk = []
        cost = 0
        for line, call, estimate in calls:
            if chunk and (cost + estimate > 1600 or len(chunk) == 20):
                chunks.append(chunk)
                chunk, cost = [], 0
            chunk.append(f'  // src/regexp/{table}:{line}\n' + call)
            cost += estimate
        if chunk:
            chunks.append(chunk)
        name = {'testdata/re2-search.txt': 're2', 'find_test.go': 'find',
                'syntax/parse_test.go': 'invalid'}[table]
        for index, chunk in enumerate(chunks, 1):
            path = OUT / f'SEM-3-regex-{name}-{index:03}-run.hir'
            path.write_text(HEADER + harness + '\npub fn main() -> Result[(), ()] {\n' +
                            '\n'.join(chunk) + '\n  Ok(())\n}\n')
            manifest = json.loads((OUT / 'SEM-3-regex-go-1-run.hir.json').read_text())
            manifest['sources'][0]['path'] = path.name
            path.with_suffix('.hir.json').write_text(json.dumps(manifest, indent=2) + '\n')
            programs.append(path)

    table = 'testdata/re2-search.txt'
    calls = []
    patterns = set()
    for line, pattern, text, span in re2_rows((args.go / 'src/regexp' / table).read_text()):
        counts['re2 total'] += 1
        decoded = decode(table, line, pattern, text)
        if decoded is None:
            continue
        pattern, text = decoded
        # Go exec_test.go:153-159 also skips RE2's byte-interior \\B matches.
        if '\\B' in pattern and not text.isascii():
            skip(table, line, 'RE2 byte-interior boundary; Go and Hirsel use scalar boundaries')
            continue
        patterns.add(pattern)
        calls.append((line, search_call(pattern, text, span),
                      max(40, len(pattern) * (len(text) + 1))))
    counts['re2 imported'] = len(calls)
    counts['re2 distinct patterns'] = len(patterns)
    assert counts['re2 total'] == 1888
    write(table, calls, SEARCH)

    table = 'find_test.go'
    calls = []
    for line, pattern, text, maximum, span in find_rows((args.go / 'src/regexp' / table).read_text()):
        counts['find total'] += 1
        decoded = decode(table, line, pattern, text)
        if decoded is None:
            continue
        if maximum == 0:
            skip(table, line, 'max=0: Go defines no single-Find expectation')
            continue
        pattern, text = decoded
        calls.append((line, search_call(pattern, text, span), max(40, len(pattern) * (len(text) + 1))))
    counts['find imported'] = len(calls)
    assert counts['find total'] == 94
    write(table, calls, SEARCH)

    table = 'syntax/parse_test.go'
    calls = []
    for line, raw in expressions((args.go / 'src/regexp' / table).read_text()):
        counts['invalid total'] += 1
        decoded = decode(table, line, raw)
        if decoded is None:
            continue
        pattern, _ = decoded
        if line == 504:
            # Go's height cap is not Hirsel's caller-supplied size bound.
            skip(table, line, 'Go-only nesting cap; Hirsel has explicit stacks (regex-depth case)')
            continue
        size_error = ('{' in pattern or line == 505) and pattern != 'x{2,1}'
        call = f'  invalid({literal(pattern)}, {str(size_error).lower()})'
        if line in LARGE_INVALID:
            path = FIXTURES / f'regex-go-invalid-{line}.hir'
            path.write_text('// Go syntax/parse_test.go:' + str(line) + ' (ebe2feef; BSD-3-Clause).\n' +
                            '// Exact vector exceeds the corpus 1M-step budget; run by stdlib_patterns.rs.\n' +
                            INVALID + '\npub fn main() -> Result[(), ()] {\n' +
                            call + '\n  Ok(())\n}\n')
            manifest = json.loads((FIXTURES / 'yaml-key-explicit.hir.json').read_text())
            manifest['sources'][0]['path'] = path.name
            path.with_suffix('.hir.json').write_text(json.dumps(manifest, indent=2) + '\n')
            large_programs.append(path)
        else:
            calls.append((line, call, max(40, len(pattern))))
    counts['invalid imported'] = len(calls) + len(large_programs)
    counts['invalid in corpus'] = len(calls)
    counts['invalid in Rust execution fixtures'] = len(large_programs)
    assert counts['invalid total'] == 44
    write(table, calls, INVALID)
    assert len(skipped) + sum(counts[name + ' imported'] for name in ('re2', 'find', 'invalid')) == 2026

    # Register generated programs without disturbing other lanes' cases.
    passing = ROOT / 'conformance/passing.txt'
    names = {str(path.relative_to(ROOT)) for path in programs}
    existing = [name for name in passing.read_text().splitlines()
                if not re.fullmatch(r'conformance/SEM/SEM-3-regex-(re2|find|invalid)-\d{3}-run.hir', name)]
    passing.write_text('\n'.join(sorted(set(existing) | names)) + '\n')
    if args.hirsel:
        for path in [*programs, *large_programs, ROOT / 'stdlib/std@1/regex.hir',
                     OUT / 'SEM-3-regex-edges-run.hir', OUT / 'SEM-3-regex-braces-run.hir']:
            subprocess.run([str(args.hirsel.resolve()), 'fmt', str(path)], check=True)
    report = ['# Go regexp vector import', '', f'Reference: golang/go `{COMMIT}`.', '',
              'Generated by `tools/generate-regex-test.py`; each imported call cites its source line.', '',
              '| Count | Value |', '|---|---:|']
    report += [f'| {name} | {count} |' for name, count in sorted(counts.items())]
    report += ['', f'{len(programs)} independent corpus programs. Search expectations use only the first',
               'whole span; captures, all-match iteration and alternate APIs are outside the public API.',
               'Every search requires successful compilation. Invalid cases distinguish Syntax from',
               'ProgramTooLarge at a caller-supplied limit of 1000: Go has fixed count/height limits.', '',
               'Three invalidRegexps (:505-507) individually exceed the corpus 1M-step budget.',
               'Their exact generated programs live in crates/hirsel-driver/tests/fixtures/',
               'regex-go-invalid-*.hir and run as bounded Rust execution tests. No corpus',
               'step limit is raised. Search batches have at most 20 calls, after two original',
               'anchor-heavy batches exhausted fuel when combined in one program.', '',
               'Before this import the three regex-go programs held 96 checks over 63 patterns,',
               'covering 153 RE2 source rows. Coverage is now 1524 source rows over 396 patterns',
               '(1371 previously uncovered rows). The audit counted 2 applicable findTests rows',
               'and no verbatim invalidRegexps; this import carries 80 and 26 respectively.', '',
               '## Deliberate differences from the reference', '',
               '- The documented scalar dialect omits flags, named groups, property/POSIX classes,',
               '  byte matching, quoted literals and numeric escapes. Structural groups are retained;',
               '  only whole spans are exposed, so submatch indices and all-match APIs are omitted.',
               '- Strings must be valid UTF-8. Go byte strings with malformed UTF-8 cannot reach',
               '  regex.compile/find; text.finish rejects them before a String exists.',
               '- RE2 byte-interior non-boundaries are skipped exactly as Go exec_test.go:153-159',
               '  does: Hirsel searches only Unicode scalar boundaries.',
               '- Repeat recognition follows Go parse.go:996-1015,1099-1141,1272-1303, including',
               '  literal incomplete forms and leading zeroes. Hirsel retains checked u64 counts',
               '  and a caller-supplied program bound instead of Go\'s fixed repeat-count cap.',
               '- Go rejects 1000 empty nested groups at its height limit (parse_test.go:504).',
               '  Hirsel uses explicit stacks and accepts them; the regex-depth case guards that',
               '  design. Nested nullable stars at :505 exceed the 1000-slot bound and are tested.',
               '- Original regex-go samples remain as regressions; row counts above describe the',
               '  complete newly imported tables, including their duplicate pattern/text pairs.',
               '- The existing reduced-dialect context-stack parser is retained; only repeat-form',
               '  recognition is ported here. Go\'s full flags/capture parser and simplification',
               '  passes serve APIs outside this dialect. The existing ordered Pike VM retains',
               '  explicit DFS stacks and deterministic work charges instead of Go\'s recursive',
               '  epsilon closure, to enforce caller bounds without host stack exhaustion.', '',
               '## Exclusions (every omitted source row)', '', '| Source | Reason |', '|---|---|']
    report += [f'| src/regexp/{table}:{line} | {reason} |' for table, line, reason in skipped]
    (ROOT / 'reports/regex-vectors.md').write_text('\n'.join(report) + '\n')
    print(json.dumps(dict(counts), indent=2))
    print(f'{len(programs)} programs; {len(skipped)} excluded rows')


if __name__ == '__main__':
    main()
