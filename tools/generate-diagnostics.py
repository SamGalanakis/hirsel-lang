#!/usr/bin/env python3
"""Generate the diagnostic repair reference from the compiler's guidance table."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent.parent
INTRO = """# Fixing diagnostics

Each diagnostic cites a stable rule and keeps its primary source location. Secondary
labels identify the supplied value, its origin and the receiving requirement when
those sites are available. `help` notes describe possible repairs; check the stated
conditions before editing. A JSON `fix` contains a half-open UTF-8 byte span and a
suggested replacement for a mechanical edit. Apply it only to the same source revision.

This reference is generated by `tools/generate-diagnostics.py` from
`crates/hirsel-diag/src/guidance.tsv`, the same repair guidance used by diagnostics.
More specific repairs in a diagnostic take precedence over the typical fixes below.
"""


def render():
    sections = [INTRO]
    for line in (ROOT / "crates/hirsel-diag/src/guidance.tsv").read_text().splitlines():
        rule, title, meaning, help_text = line.split("\t")
        help_text = help_text.removeprefix("help: ")
        sections.append(f"\n## {rule}: {title}\n\n{meaning}\n\nTypical fix: {help_text}\n")
    return "".join(sections)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "docs/diagnostics.md"
    expected = render()
    if args.check:
        if target.read_text() != expected:
            parser.exit(1, "docs/diagnostics.md is stale; run tools/generate-diagnostics.py\n")
    else:
        target.write_text(expected)
